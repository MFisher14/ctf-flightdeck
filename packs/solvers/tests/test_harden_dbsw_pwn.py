# ---- Kconfig/sysctl/cmdline documented text forms ----


def test_kconfig_vector_lock_against_documented_text_semantics() -> None:
    config_text = (
        "CONFIG_USER_NS=y\n"
        "CONFIG_IO_URING=y\n"
        "CONFIG_MODULE_TEST=m\n"
        "# CONFIG_USERFAULTFD is not set\n"
        'CONFIG_MODPROBE_PATH="/sbin/\\"helper"\n'
    )
    parsed = kconfig.parse_kconfig(config_text)
    assert dict(parsed.values) == {
        "CONFIG_USER_NS": "y",
        "CONFIG_IO_URING": "y",
        "CONFIG_MODULE_TEST": "m",
        "CONFIG_USERFAULTFD": "n",
        "CONFIG_MODPROBE_PATH": '/sbin/"helper',
    }
    assert parsed.state("CONFIG_USER_NS") == "on"
    assert parsed.state("CONFIG_MODULE_TEST") == "module"
    assert parsed.state("CONFIG_USERFAULTFD") == "off"

    sysctls = kconfig.parse_sysctl_facts(
        "/proc/sys/kernel/io_uring_disabled=1\nvm/unprivileged_userfaultfd=0\n"
    )
    assert dict(sysctls.values) == {
        "kernel.io_uring_disabled": "1",
        "vm.unprivileged_userfaultfd": "0",
    }
    cmdline = kconfig.parse_cmdline("quiet pti=off pti=on slab_nomerge")
    assert cmdline.tokens == ("quiet", "pti=off", "pti=on", "slab_nomerge")
    assert cmdline.value("pti") == "on"  # kernel command-line policy: last token.

    profile = kconfig.profile_kernel(
        config_text,
        "kernel.io_uring_disabled=1\nvm.unprivileged_userfaultfd=0",
    )
    assert profile.get("io_uring").effective_state == "restricted"
    assert profile.get("userfaultfd_kernel_faults").effective_state == "off"


