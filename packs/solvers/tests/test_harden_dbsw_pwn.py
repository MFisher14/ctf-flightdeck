def _only_declared(call: Callable[[], object], declared: type[Exception]) -> None:
    """Accept a clean result or the engine's one declared input exception."""

    try:
        call()
    except declared:
        return
    except Exception as leaked:  # pragma: no cover - assertion path
        pytest.fail(
            f"leaked {type(leaked).__name__}, expected only {declared.__name__}: {leaked}"
        )


# ---- glibc: independent request2size and largebin_index_64 translations ----


def _request2size_x86_64(request: int) -> int:
    # glibc SIZE_SZ=8, MALLOC_ALIGNMENT=16, MINSIZE=0x20.
    return max(0x20, (request + 8 + 15) & ~15)


def _largebin_index_64(size: int) -> int:
    # Literal translation of glibc malloc.c's largebin_index_64 macro.
    if (size >> 6) <= 48:
        return 48 + (size >> 6)
    if (size >> 9) <= 20:
        return 91 + (size >> 9)
    if (size >> 12) <= 10:
        return 110 + (size >> 12)
    if (size >> 15) <= 4:
        return 119 + (size >> 15)
    if (size >> 18) <= 2:
        return 124 + (size >> 18)
    return 126


def test_glibc_vector_lock_against_published_allocator_macros() -> None:
    for request in (0, 1, 24, 25, 120, 121, 1000, 1001, 0x418):
        plan = glibc.plan_allocation("2.43", request)
        assert plan.chunk_size == _request2size_x86_64(request)

    for chunk in (0x400, 0xC30, 0xC40, 0x29F0, 0x2A00, 0xA000, 0x40000):
        assert glibc.largebin_index_64(chunk) == _largebin_index_64(chunk)

    # Tagged-release transitions documented by upstream source changes.
    assert glibc.release_profile("2.40").calloc_tcache_first is False
    assert glibc.release_profile("2.41").calloc_tcache_first is True
    assert glibc.release_profile("2.42").tcache_total_bins == 76
    assert glibc.release_profile("2.43").fastbins_present is False


