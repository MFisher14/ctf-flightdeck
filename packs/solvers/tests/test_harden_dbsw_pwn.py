def test_pagegeo_vector_lock_against_linux_address_formulae() -> None:
    address = 0x12345678
    expected_indices = {
        "pte": (address >> 12) & 0x1FF,
        "pmd": (address >> 21) & 0x1FF,
        "pud": (address >> 30) & 0x1FF,
        "pgd": (address >> 39) & 0x1FF,
    }
    split = pagegeo.decompose_page_table(address, **PT).as_dict()
    assert split["offset"] == address & 0xFFF
    assert split["indices"] == expected_indices
    assert pagegeo.compose_page_table(
        expected_indices, offset=address & 0xFFF, **PT
    ).address == address

    pfn = 4
    descriptor = VMEMMAP + pfn * 0x40
    assert pagegeo.map_pfn(pfn, **MEM).descriptor_address == descriptor
    assert pagegeo.map_descriptor(descriptor, **MEM).pfn == pfn

    physical = 0x123456
    virtual = 0xFFFF888000023456
    assert pagegeo.physical_to_direct_map(physical, **DIRECT).virtual_address == virtual
    assert pagegeo.direct_map_to_physical(virtual, **DIRECT).physical_address == physical
    assert pagegeo.pfn_to_direct_map(
        0x123, page_offset=0x456, page_shift=12, **DIRECT
    ).virtual_address == virtual
    inverse = pagegeo.direct_map_to_pfn(virtual, page_shift=12, **DIRECT)
    assert (inverse.pfn, inverse.page_offset) == (0x123, 0x456)

    patch = pagegeo.plan_descriptor_pointer_patch(
        4, 5, **MEM,
        pointer_width=8, overwrite_offset=0, overwrite_width=1,
        byteorder="little",
    )
    # VMEMMAP+4*0x40 -> VMEMMAP+5*0x40 changes low byte 0x00 to 0x40.
    assert (patch.source_pointer, patch.target_pointer, patch.patch_hex) == (
        VMEMMAP + 0x100, VMEMMAP + 0x140, "40"
    )

    landing = pagegeo.plan_page_uaf_landing(**UAF).as_dict()
    base = 0x200 << 12
    expected_fields = [base + index * 0x100 + 0x20 for index in range(16)]
    assert [row["field_start"] for row in landing["reachable_fields"]] == expected_fields


