# ---- eBPF verifier: literal kernel verifier-log semantics ----


def test_ebpf_vector_lock_against_documented_verifier_state_lines() -> None:
    valid = (
        "0: R0=scalar(umin=0,umax=15,var_off=(0x0; 0xf)) "
        "R10=fp0\n"
    )
    parsed = ebpf.parse_verifier_log(valid)
    assert len(parsed.states) == 1
    assert parsed.states[0].pc == 0
    assert [register.register for register in parsed.states[0].registers] == ["R0", "R10"]
    assert [register.number for register in parsed.states[0].registers] == [0, 10]
    assert ebpf.audit_verifier_log(valid).findings == ()

    # Bounds with lower > upper are contradictory by integer interval semantics.
    bad = "7: R0=scalar(umin=10,umax=9,var_off=(0x0; 0xf))\n"
    codes = {finding.code for finding in ebpf.audit_verifier_log(bad).findings}
    assert "unsigned_bounds_inverted" in codes


def test_ebpf_entrypoints_fail_closed_under_log_fuzz() -> None:
    rng = random.Random(0xDB5704)
    valid = b"0: R0=scalar(umin=0,umax=15,var_off=(0x0; 0xf)) R10=fp0\n"
    random_blob = bytes(rng.randrange(256) for _ in range(4096))
    flipped = bytearray(valid)
    flipped[len(flipped) // 2] ^= 0x20
    corpus = (
        b"",
        random_blob,
        valid[:-7],
        bytes(flipped),
        b"A" * (ebpf.MAX_LOG_BYTES + 1),
    )
    for function in (ebpf.parse_verifier_log, ebpf.audit_verifier_log):
        for sample in corpus:
            _only_declared(lambda f=function, s=sample: f(s), ebpf.WPGAPEBPFError)
    for argv in ([], [None], ["\ud800"], ["--bogus"], ["9" * 10000]):
        assert ebpf.main(argv) in (0, 2)


