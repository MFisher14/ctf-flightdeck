"""Independent AIS bit writer, not pyais encoder, plus published capture."""
import pytest
import transport_ais as ais


def bits(length, kind, fields=()):
    result = ['0'] * length
    for offset, width, value in [(0, 6, kind), (8, 30, 123456789), *fields]:
        value %= 1 << width
        result[offset:offset + width] = format(value, f'0{width}b')
    return ''.join(result)


def sentence(payload, total=1, number=1, seq='', channel='A', fill=None):
    if fill is None:
        fill = (-len(payload)) % 6
        payload += '0' * fill
    chars = []
    for offset in range(0, len(payload), 6):
        value = int(payload[offset:offset + 6], 2)
        chars.append(chr(value + (48 if value < 40 else 56)))
    body = f'AIVDM,{total},{number},{seq},{channel},{"".join(chars)},{fill}'
    check = 0
    for char in body:
        check ^= ord(char)
    return f'!{body}*{check:02X}'


def sixtext(value):
    return ''.join(f'{ord(char) & 63:06b}' for char in value)


@pytest.mark.parametrize('kind,length', [(1,168),(2,168),(3,168),(4,168),(5,424),(6,88),(7,72),(8,56),(9,168),(10,72),(11,168),(12,72),(13,72),(14,40),(15,88),(16,96),(17,80),(18,168),(19,312),(20,72),(21,272),(22,168),(23,160),(24,160),(25,40),(26,60),(27,96)])
def test_all_message_types_independent_bit_layout(kind, length):
    record = ais.parse_ais(sentence(bits(length, kind)))[0]
    assert record['message_type'] == kind
    assert record['decoded']['mmsi'] == 123456789
    assert record['bit_length'] == length


def test_published_pyais_capture():
    # Published fixed capture, not generated by either engine or library encoder.
    # https://github.com/M0r13n/pyais README
    raw = '!AIVDM,1,1,,B,15NG6V0P01G?cFhE`R2IU?wn28R>,0*05'
    decoded = ais.parse_ais(raw)[0]['decoded']
    # README prose currently lists different coordinates/MMSI than its wire bytes.
    # Values below use independent integer field extraction at ITU bit offsets.
    assert decoded['mmsi'] == 367380120
    assert decoded['lat'] == pytest.approx(37.80694833333333, abs=1e-5)
    assert decoded['lon'] == pytest.approx(-122.40433333333333, abs=1e-5)


def test_long_range_signed_position():
    raw = bits(96, 27, [(40,4,5), (44,18,-73440), (62,17,22680), (79,6,14), (85,9,271)])
    decoded = ais.parse_ais(sentence(raw))[0]['decoded']
    assert decoded['lon'] == -122.4
    assert decoded['lat'] == 37.8
    assert decoded['speed'] == 14
    assert decoded['course'] == 271


def test_text_and_binary_independent_fields():
    payload = bits(40, 14) + sixtext('MEET AT PIER 7')
    assert ais.parse_ais(sentence(payload))[0]['decoded']['text'] == 'MEET AT PIER 7'
    payload = bits(56, 8, [(40,10,999),(50,6,63)]) + '1010010111000011'
    record = ais.parse_ais(sentence(payload))[0]
    assert record['application_bits'] == '1010010111000011'
    assert record['decoded']['dac'] == 999
    assert record['decoded']['fid'] == 63
    assert record['application_bit_length'] == 16


def test_static_part_b_and_aid_name():
    raw = list(bits(168,24, [(38,2,1),(40,8,70),(132,9,23),(141,9,45)]))
    raw[90:132] = sixtext('CALL123')
    decoded = ais.parse_ais(sentence(''.join(raw)))[0]['decoded']
    assert decoded['callsign'] == 'CALL123'
    assert decoded['ship_type'] == 70
    assert decoded['to_bow'] == 23
    raw = list(bits(272,21,[(38,5,5),(253,1,1)]))
    raw[43:163] = sixtext('VIRTUAL BUOY'.ljust(20,'@'))
    decoded = ais.parse_ais(sentence(''.join(raw)))[0]['decoded']
    assert decoded['name'] == 'VIRTUAL BUOY'


def test_multipart_and_collision():
    payload = bits(424,5)
    first = sentence(payload[:360],2,1,'4',fill=0)
    last = sentence(payload[360:],2,2,'4')
    assert ais.parse_ais(first+'\n'+last)[0]['fragments'] == 2
    for text in (first, last, first+'\n'+first, last+'\n'+first):
        with pytest.raises(ais.TransportAISError):
            ais.parse_ais(text)


@pytest.mark.parametrize('raw', [None, b'x', 4, '', 'not AIS', '!AIVDM,1,1,,A,111,0*00'])
def test_bad_input_contract(raw):
    if raw == '':
        assert ais.parse_ais(raw) == []
    else:
        with pytest.raises(ais.TransportAISError):
            ais.parse_ais(raw)


def test_truncation_checksum_and_fill_rejected():
    with pytest.raises(ais.TransportAISError):
        ais.parse_ais(sentence(bits(162,1)))
    line = sentence(bits(168,1))
    with pytest.raises(ais.TransportAISError):
        ais.parse_ais(line[:-2]+'FF')
    with pytest.raises(ais.TransportAISError):
        ais.parse_ais(sentence(bits(40,14)+'11',fill=2))


def test_cli_guard(tmp_path):
    assert ais.main(['--help']) == 0
    assert ais.main(['--unknown']) == 2
    assert ais.main([str(tmp_path/'missing')]) == 2


def test_coordinates_unavailable_vs_invalid():
    unavailable = bits(168, 1, [(61,28,181*600000),(89,27,91*600000)])
    record = ais.parse_ais(sentence(unavailable))[0]['decoded']
    assert record['lat'] is None and record['lon'] is None
    for value in (181*600000+10, -181*600000):
        with pytest.raises(ais.TransportAISError):
            ais.parse_ais(sentence(bits(168,1,[(61,28,value)])))


def test_variable_octet_alignment_and_nul_path():
    for kind,length in ((8,57),(17,81),(21,273)):
        with pytest.raises(ais.TransportAISError):
            ais.parse_ais(sentence(bits(length,kind)))
    assert ais.main(['bad\x00path']) == 2


def test_documented_padding_variants():
    # GPSD AIVDM: type24A may include 8 spare bits; type15 uses byte padding.
    assert ais.parse_ais(sentence(bits(168,24)))[0]['message_type'] == 24
    assert ais.parse_ais(sentence(bits(112,15)))[0]['message_type'] == 15
    for kind, base in ((12,72),(14,40)):
        payload = bits(base,kind) + sixtext('HELLO')
        payload += '0' * ((-len(payload)) % 8)
        assert ais.parse_ais(sentence(payload))[0]['decoded']['text'] == 'HELLO'
    with pytest.raises(ais.TransportAISError):
        ais.parse_ais(sentence(bits(168,24,[(167,1,1)])))
