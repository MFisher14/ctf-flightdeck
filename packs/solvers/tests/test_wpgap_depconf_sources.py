def test_cli_non_integer_system_exit_normalizes_to_two(monkeypatch):
    def unusual_exit(_self, _argv=None):
        raise SystemExit("not-an-integer")

    monkeypatch.setattr(argparse.ArgumentParser, "parse_args", unusual_exit)
    assert depconf.main([]) == 2


def test_cli_success_prints_machine_readable_offline_report(tmp_path, capsys):
    requirements = tmp_path / "requirements.txt"
    requirements.write_text("acme==1.0\n", encoding="utf-8")
    code = depconf.main(
        [
            "--internal",
            "pip:acme",
            "--internal-host",
            INTERNAL_HOST,
            str(requirements),
        ]
    )
    captured = capsys.readouterr()
    assert code == 0
    report = json.loads(captured.out)
    assert report["offline"] is True
    assert report["network_requests"] == 0
    assert _package(report, "pip", "acme")["outcome"] == "public-routed"
