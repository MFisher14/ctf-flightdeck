INTERNAL_HOST = "packages.corp.example"


def _package(report: dict, ecosystem: str, name: str) -> dict:
    hits = [
        item
        for item in report["packages"]
        if item["ecosystem"] == ecosystem and item["name"] == name
    ]
    assert len(hits) == 1, (ecosystem, name, report["packages"])
    return hits[0]


def _audit(files: dict[str, str | bytes], ecosystem: str, *names: str) -> dict:
    return depconf.audit_configs(
        files,
        internal_names={ecosystem: list(names)},
        internal_hosts=[INTERNAL_HOST],
    )


def test_report_contract_is_explicitly_offline_and_bounded_to_supplied_evidence():
    report = _audit({"requirements.txt": "acme_core==1.2.3\n"}, "pip", "acme_core")
    assert report["kind"] == "dependency-source-precedence-audit"
    assert report["offline"] is True
    assert report["network_requests"] == 0
    assert isinstance(report["packages"], list)
    assert isinstance(report["clues"], list)
    assert isinstance(report["configs"], list)
    assert isinstance(report["limitations"], list)
    assert _package(report, "pip", "acme-core")["outcome"] == "public-routed"


