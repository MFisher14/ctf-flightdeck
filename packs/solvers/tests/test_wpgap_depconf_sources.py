def test_urls_are_redacted_and_host_roles_require_exact_hostname_match():
    secret_url = (
        "https://alice:hunter2@packages.corp.example/"
        "token-secret/simple?api_key=QUERYSECRET#FRAGMENTSECRET"
    )
    report = depconf.audit_configs(
        {
            "pip.conf": f"[global]\nindex-url = {secret_url}\n",
            "requirements.txt": "acme==1\n",
        },
        internal_names={"pip": ["acme"]},
        internal_hosts=[INTERNAL_HOST],
    )
    rendered = json.dumps(report)
    for secret in ("alice", "hunter2", "token-secret", "QUERYSECRET", "FRAGMENTSECRET"):
        assert secret not in rendered
    assert _package(report, "pip", "acme")["sources"][0]["role"] == "internal"

    lookalike = _audit(
        {
            "pip.conf": "[global]\nindex-url=https://pypi.org.attacker.invalid/simple\n",
            "requirements.txt": "acme==1\n",
        },
        "pip",
        "acme",
    )
    item = _package(lookalike, "pip", "acme")
    assert item["sources"][0]["role"] == "unknown"
    assert item["outcome"] == "indeterminate"

    unsupported = _audit(
        {"pip.conf": "[global]\nindex-url=javascript://packages.corp.example/simple\n"},
        "pip",
        "acme",
    )
    assert _package(unsupported, "pip", "acme")["outcome"] == "indeterminate"


