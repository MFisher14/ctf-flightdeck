# Literal Linux UAPI values, deliberately not imported from the engines.
LD_W_ABS, JMP_JEQ_K, RET_K = 0x20, 0x15, 0x06
AUDIT_ARCH_X86_64 = 0xC000003E
RET_KILL_PROCESS, RET_USER_NOTIF = 0x80000000, 0x7FC00000
RET_TRACE, RET_LOG, RET_ALLOW = 0x7FF00000, 0x7FFC0000, 0x7FFF0000
RET_ERRNO_EPERM = 0x00050001
# Published 30-byte zbt vector: shell-storm.org/shellcode/files/shellcode-603.html
AMD64_EXECVE = bytes.fromhex(
    "4831d248bb2f2f62696e2f736848c1eb08534889e750574889e6b03b0f05"
)


def pack_rows(rows, endian="little"):
    prefix = "<" if endian == "little" else ">"
    return b"".join(struct.pack(prefix + "HBBI", *row) for row in rows)


def policy_rows(actions=()):
    """Hand-built arch guard, nr/action pairs, then EPERM default."""
    rows = [
        (LD_W_ABS, 0, 0, 4),
        (JMP_JEQ_K, 1, 0, AUDIT_ARCH_X86_64),
        (RET_K, 0, 0, RET_KILL_PROCESS),
        (LD_W_ABS, 0, 0, 0),
    ]
    for number, action in actions:
        rows.extend(((JMP_JEQ_K, 0, 1, number), (RET_K, 0, 0, action)))
    rows.append((RET_K, 0, 0, RET_ERRNO_EPERM))
    return rows


READ_POLICY_ROWS = policy_rows(((0, RET_ALLOW),))
READ_POLICY = pack_rows(READ_POLICY_ROWS)


def clean_call(error_type, function, *args, **kwargs):
    try:
        return function(*args, **kwargs)
    except error_type:
        return None
    except BaseException as exc:
        pytest.fail(f"undeclared {type(exc).__name__}: {exc}")


def replace_payload(build, payload):
    placements = dict(build.placements)
    widths = dict(build.widths)
    for name, width in widths.items():
        remaining = len(payload) - placements[name]
        if remaining < width:
            assert remaining > 0
            widths[name] = remaining
    placements["end"] = len(payload)
    return PayloadBuild(
        payload, placements, widths, architecture=build.architecture,
        strategy=build.strategy, base_address=build.base_address,
        metadata=dict(build.metadata),
    )


