def test_packed_filter_truncation_bitflips_random_and_oversize_fail_closed():
    for cut in range(len(READ_POLICY)):
        try:
            program = seccomp.parse_sock_filters(READ_POLICY[:cut])
        except seccomp.SeccompError:
            continue
        clean_call(seccomp.SeccompError, seccomp.validate_program, program)
    for index in range(len(READ_POLICY)):
        changed = bytearray(READ_POLICY)
        changed[index] ^= 1 << (index % 8)
        try:
            program = seccomp.parse_sock_filters(changed)
        except seccomp.SeccompError:
            continue
        clean_call(seccomp.SeccompError, seccomp.validate_program, program)
        try:
            seccomp.validate_program(program)
        except seccomp.SeccompError:
            continue
        result = clean_call(seccomp.SeccompError, seccomp.execute_filter,
                            program, 0, AUDIT_ARCH_X86_64)
        assert result is None or 0 <= result <= 0xFFFFFFFF
    rng = random.Random(0x5ECC0)
    for size in range(128):
        raw = rng.randbytes(size)
        clean_call(seccomp.SeccompError, seccomp.parse_sock_filters, raw)
        assert isinstance(seccomp.detect_seccomp(raw), dict)
        assert isinstance(seccomp.find_embedded_filters(raw), list)
        clean_call(patterns.SeccompPatternError, patterns.decode_filter, raw)
    oversized = bytes((seccomp.MAX_INSNS + 1) * 8)
    clean_call(seccomp.SeccompError, seccomp.parse_sock_filters, oversized)
    clean_call(patterns.SeccompPatternError, patterns.decode_filter, oversized)


