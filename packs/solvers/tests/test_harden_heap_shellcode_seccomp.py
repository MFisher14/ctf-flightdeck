def test_published_amd64_execve_vector_and_capstone_oracle():
    built = shellcode.build_shellcode("execve", "amd64", avoid={0})
    assert built.raw == AMD64_EXECVE
    assert not set(built.raw) & {0}
    assert built.syscalls == ("execve",) and built.syscall_numbers == (59,)
    decoded = list(capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64).disasm(built.raw, 0))
    assert [ins.mnemonic for ins in decoded[-3:]] == ["mov", "mov", "syscall"]
    assert decoded[-2].op_str == "al, 0x3b" and b"//bin/sh" in built.raw
    assert built.as_dict()["raw_hex"] == AMD64_EXECVE.hex()


