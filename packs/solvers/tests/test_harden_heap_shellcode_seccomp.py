        (patterns.build_orw_plan, broad_report, {"path": ""}),
        (patterns.build_orw_plan, broad_report, {"path": "\ud800"}),
        (patterns.build_orw_plan, broad_report, {"max_bytes": 0}),
        (patterns.build_fd_reuse_plan, broad_report, {
            "source_fd": 1, "destination_fd": 1,
        }),
