F = descriptor_pb2.FieldDescriptorProto


def _field(message, name, number, kind, *, repeated=False, type_name=None):
    field = message.field.add()
    field.name = name
    field.number = number
    field.label = F.LABEL_REPEATED if repeated else F.LABEL_OPTIONAL
    field.type = kind
    if type_name is not None:
        field.type_name = type_name


def _tak_message_class():
    """Build a protobuf-runtime oracle from the published TAK v1 field map."""
    file_desc = descriptor_pb2.FileDescriptorProto(
        name="published_tak_v1_oracle.proto",
        package="atakmap.commoncommo.protobuf.v1",
        syntax="proto3",
    )
    package = ".atakmap.commoncommo.protobuf.v1."

    string_messages = {
        "Contact": (("endpoint", 1), ("callsign", 2), ("altendpoints", 3)),
        "Group": (("name", 1), ("role", 2)),
        "PrecisionLocation": (("geopointsrc", 1), ("altsrc", 2)),
        "Takv": (("device", 1), ("platform", 2), ("os", 3), ("version", 4)),
    }
    for message_name, fields in string_messages.items():
        message = file_desc.message_type.add(name=message_name)
        for field_name, number in fields:
            _field(message, field_name, number, F.TYPE_STRING)

    status = file_desc.message_type.add(name="Status")
    _field(status, "battery", 1, F.TYPE_UINT32)
    track = file_desc.message_type.add(name="Track")
    _field(track, "speed", 1, F.TYPE_DOUBLE)
    _field(track, "course", 2, F.TYPE_DOUBLE)

    detail = file_desc.message_type.add(name="Detail")
    extension = detail.nested_type.add(name="ExtensionEncodedDetail")
    _field(extension, "extensionId", 1, F.TYPE_UINT32)
    _field(extension, "data", 2, F.TYPE_BYTES)
    _field(detail, "xmlDetail", 1, F.TYPE_STRING)
    for number, (field_name, target) in enumerate(
        (
            ("contact", "Contact"),
            ("group", "Group"),
            ("precisionLocation", "PrecisionLocation"),
            ("status", "Status"),
            ("takv", "Takv"),
            ("track", "Track"),
        ),
        start=2,
    ):
        _field(detail, field_name, number, F.TYPE_MESSAGE, type_name=package + target)
    _field(
        detail,
        "extension",
        8,
        F.TYPE_MESSAGE,
        repeated=True,
        type_name=package + "Detail.ExtensionEncodedDetail",
    )

    event = file_desc.message_type.add(name="CotEvent")
    for name, number in (
        ("type", 1), ("access", 2), ("qos", 3), ("opex", 4), ("uid", 5),
        ("how", 9), ("caveat", 16), ("releasableTo", 17),
    ):
        _field(event, name, number, F.TYPE_STRING)
    for name, number in (("sendTime", 6), ("startTime", 7), ("staleTime", 8)):
        _field(event, name, number, F.TYPE_UINT64)
    for name, number in (
        ("lat", 10), ("lon", 11), ("hae", 12), ("ce", 13), ("le", 14),
    ):
        _field(event, name, number, F.TYPE_DOUBLE)
    _field(event, "detail", 15, F.TYPE_MESSAGE, type_name=package + "Detail")

    control = file_desc.message_type.add(name="TakControl")
    _field(control, "minProtoVersion", 1, F.TYPE_UINT32)
    _field(control, "maxProtoVersion", 2, F.TYPE_UINT32)
    _field(control, "contactUid", 3, F.TYPE_STRING)
    _field(control, "extensionIds", 4, F.TYPE_UINT32, repeated=True)

    message = file_desc.message_type.add(name="TakMessage")
    _field(message, "takControl", 1, F.TYPE_MESSAGE, type_name=package + "TakControl")
    _field(message, "cotEvent", 2, F.TYPE_MESSAGE, type_name=package + "CotEvent")

    pool = descriptor_pool.DescriptorPool()
    pool.Add(file_desc)
    return message_factory.GetMessageClass(
        pool.FindMessageTypeByName("atakmap.commoncommo.protobuf.v1.TakMessage")
    )


