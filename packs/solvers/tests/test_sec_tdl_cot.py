def test_protobuf_empty_message_control_defaults_precedence_and_packed_bound():
    empty = TAK_MESSAGE().SerializeToString(deterministic=True)
    assert empty == b""
    assert TAK_MESSAGE.FromString(empty) == TAK_MESSAGE()
    raw_report = cot.parse_tak_payload(empty)
    assert raw_report["payload_length"] == 0
    assert raw_report["finding"].startswith("empty TakMessage")
    assert cot.parse_tak_mesh(b"\xbf\x01\xbf")["message"]["payload_length"] == 0
    assert cot.parse_tak_stream(b"\xbf\x00")["frames"][0]["payload_length"] == 0

    control = TAK_MESSAGE()
    control.takControl.SetInParent()
    control_report = cot.parse_tak_payload(control.SerializeToString())["tak_control"]
    assert control_report["min_proto_version"] == 1
    assert control_report["max_proto_version"] == 1

    conflict = TAK_MESSAGE()
    conflict.cotEvent.detail.xmlDetail = '<__group name="xml"/>'
    conflict.cotEvent.detail.group.name = "typed"
    detail = cot.parse_tak_payload(conflict.SerializeToString())["cot_event"]["detail"]
    assert detail["typed_xml_conflicts"] == ["__group"]
    assert "authoritative" in detail["precedence"]

    namespaced_conflict = TAK_MESSAGE()
    namespaced_conflict.cotEvent.detail.xmlDetail = (
        '<x:contact xmlns:x="urn:custom" callsign="xml"/>'
    )
    namespaced_conflict.cotEvent.detail.contact.callsign = "typed"
    namespaced_detail = cot.parse_tak_payload(
        namespaced_conflict.SerializeToString()
    )["cot_event"]["detail"]
    assert "typed_xml_conflicts" not in namespaced_detail

    empty_access = TAK_MESSAGE()
    empty_access.cotEvent.access = ""
    empty_access.cotEvent.uid = ""
    empty_event = cot.parse_tak_payload(empty_access.SerializeToString())["cot_event"]
    assert "uid" in empty_event["findings"][0]["fields"]
    assert any(item["code"] == "access_undefined_or_legacy_absent"
               for item in empty_event["findings"])

    packed = b"\x00" * (cot.MAX_PROTO_FIELDS + 1)
    inner = b"\x22" + _uvarint(len(packed)) + packed
    too_many = b"\x0a" + _uvarint(len(inner)) + inner
    with pytest.raises(cot.SecTdlCotError, match="extensionIds count"):
        cot.parse_tak_payload(too_many)


def test_documented_mesh_and_stream_framing_are_explicit():
    payload = _published_proto_vector()
    mesh = b"\xbf" + _uvarint(1) + b"\xbf" + payload
    stream = b"\xbf" + _uvarint(len(payload)) + payload

    mesh_report = cot.parse_tak_mesh(mesh)
    assert mesh_report["version"] == 1
    assert mesh_report["header_length"] == 3
    assert mesh_report["message"]["cot_event"]["uid"] == "oracle-unit-1"

    stream_report = cot.parse_tak_stream(stream + stream)
    assert stream_report["frame_count"] == 2
    assert [frame["payload_length"] for frame in stream_report["frames"]] == [
        len(payload), len(payload)
    ]
    assert stream_report["frames"][1]["message"]["cot_event"]["uid"] == "oracle-unit-1"

    with pytest.raises(cot.SecTdlCotError, match="ambiguous"):
        cot.analyze(mesh)
    with pytest.raises(cot.SecTdlCotError):
        cot.parse_tak_mesh(b"\xbf\x02\xbf" + payload)
    with pytest.raises(cot.SecTdlCotError):
        cot.parse_tak_stream(stream[:-1])


