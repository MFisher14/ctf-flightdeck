def _manifest(*entries: tuple[str, bool]) -> bytes:
    contents = "".join(
        f'<Content zipEntry="{name}" ignore="{str(ignore).lower()}"/>'
        for name, ignore in entries
    )
    return (
        '<?xml version="1.0" encoding="UTF-8"?>'
        '<MissionPackageManifest version="2">'
        '<Configuration>'
        '<Parameter name="name" value="Oracle Package"/>'
        '<Parameter name="uid" value="oracle-package-uid"/>'
        '</Configuration><Contents>' + contents +
        '</Contents></MissionPackageManifest>'
    ).encode()


def _package_bytes(*, prefix="", unsafe=False, missing=False) -> bytes:
    stream = BytesIO()
    content_entries = [("events/oracle.cot", False), ("docs/readme.txt", True)]
    if unsafe:
        content_entries.append(("../escape.txt", False))
    if missing:
        content_entries.append(("missing.bin", False))
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.writestr(prefix + "MANIFEST/manifest.xml", _manifest(*content_entries))
        archive.writestr(prefix + "events/oracle.cot", XML)
        archive.writestr(prefix + "docs/readme.txt", b"offline oracle")
        if unsafe:
            archive.writestr("../escape.txt", b"must not extract")
    return stream.getvalue()


def _hostile_inventory_package() -> bytes:
    """Make metadata attacks with stdlib ZIP, then mark two headers manually."""
    stream = BytesIO()
    with zipfile.ZipFile(stream, "w", compression=zipfile.ZIP_STORED) as archive:
        archive.writestr("MANIFEST/manifest.xml", _manifest())
        archive.writestr("../escape.txt", b"escape")
        archive.writestr("dir/../collision.txt", b"one")
        archive.writestr("collision.txt", b"two")
        archive.writestr("Case.txt", b"three")
        archive.writestr("case.txt", b"four")
        symlink = zipfile.ZipInfo("link")
        symlink.create_system = 3
        symlink.external_attr = (0o120777 << 16)
        archive.writestr(symlink, b"../outside")
        archive.writestr("encrypted.bin", b"metadata only")
        archive.writestr("unsupported.bin", b"metadata only")
    raw = bytearray(stream.getvalue())

    # Patch both local and central headers.  This is an independent byte-level
    # fixture because Python's writer intentionally cannot create encrypted or
    # unknown-compression members.
    cursor = 0
    while True:
        cursor = raw.find(b"PK\x01\x02", cursor)
        if cursor < 0:
            break
        name_length = int.from_bytes(raw[cursor + 28:cursor + 30], "little")
        extra_length = int.from_bytes(raw[cursor + 30:cursor + 32], "little")
        comment_length = int.from_bytes(raw[cursor + 32:cursor + 34], "little")
        name = bytes(raw[cursor + 46:cursor + 46 + name_length]).decode()
        local = int.from_bytes(raw[cursor + 42:cursor + 46], "little")
        if name == "encrypted.bin":
            central_flags = int.from_bytes(raw[cursor + 8:cursor + 10], "little") | 1
            local_flags = int.from_bytes(raw[local + 6:local + 8], "little") | 1
            raw[cursor + 8:cursor + 10] = central_flags.to_bytes(2, "little")
            raw[local + 6:local + 8] = local_flags.to_bytes(2, "little")
        if name == "unsupported.bin":
            raw[cursor + 10:cursor + 12] = (99).to_bytes(2, "little")
            raw[local + 8:local + 10] = (99).to_bytes(2, "little")
        cursor += 46 + name_length + extra_length + comment_length
    return bytes(raw)


def _clean_or_declared(function, data):
    try:
        return function(data)
    except Exception as exc:  # fuzz contract intentionally checks exact type
        assert type(exc) is cot.SecTdlCotError
        return None


