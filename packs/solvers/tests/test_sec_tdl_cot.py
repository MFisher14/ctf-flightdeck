def test_cot_legacy_access_drop_track_and_schema_rejections():
    legacy = XML.replace(b' access="Unclassified"', b"").replace(
        b'stale="2025-01-01T00:05:00Z"', b'stale="2024-12-31T23:59:59Z"'
    )
    report = cot.parse_cot_xml(legacy)
    assert report["event"]["drop_track"] is True
    assert {item["code"] for item in report["findings"]} >= {
        "legacy_missing_access", "drop_track_time_reversal"
    }
    bad_inputs = (
        b'<!DOCTYPE event [<!ENTITY x "boom">]><event>&x;</event>',
        XML.replace(b'lat="44.4268"', b'lat="91"'),
        XML.replace(b'<point ', b'<point><x/></point><point '),
        XML.replace(b'version="2.0"', b'version="1.0"'),
        XML.replace(b'how="m-g"', b'how="m--g"'),
        XML[:-1],
    )
    for value in bad_inputs:
        with pytest.raises(cot.SecTdlCotError):
            cot.parse_cot_xml(value)


def test_cot_xsd_all_order_exact_fraction_and_lexical_constraints():
    # Event.xsd uses xs:all, so this independently hand-built detail-before-
    # point order is valid even though most published samples use point first.
    reversed_children = (
        b'<event version="2.0" access="Unclassified" type="a-f-G" uid="u" '
        b'time="2025-01-01T00:00:00Z" start="2025-01-01T00:00:00.0000009Z" '
        b'stale="2025-01-01T00:00:00.0000001Z" how="m-g">'
        b'<detail><remarks>x</remarks></detail>'
        b'<point lat="1" lon="2" hae="3" ce="4" le="5"/></event>'
    )
    report = cot.parse_cot_xml(reversed_children)
    assert report["event"]["uid"] == "u"
    assert report["point"]["lat"] == 1.0
    assert report["event"]["drop_track"] is True

    invalid = (
        reversed_children.replace(b'time="2025-01-01T00:00:00Z"',
                                  b'time="2025-01-01T00:00:00+15:00"'),
        reversed_children.replace(b'stale="2025-01-01T00:00:00.0000001Z"',
                                  b'stale="2025-01-01T00:00:00+14:01"'),
        reversed_children.replace(b'lat="1"', b'lat="1e1"'),
        reversed_children.replace(b'version="2.0"', b'version="2e0"'),
    )
    for value in invalid:
        with pytest.raises(cot.SecTdlCotError):
            cot.parse_cot_xml(value)

    mixed_zone = reversed_children.replace(
        b'start="2025-01-01T00:00:00.0000009Z"',
        b'start="2025-01-01T00:00:00"',
    ).replace(
        b'stale="2025-01-01T00:00:00.0000001Z"',
        b'stale="2025-01-01T00:30:00+01:00"',
    )
    mixed_report = cot.parse_cot_xml(mixed_zone)
    assert mixed_report["event"]["drop_track"] is None
    assert any(item["code"] == "indeterminate_mixed_timezone_order"
               for item in mixed_report["findings"])

    namespaced = reversed_children.replace(
        b"<detail>", b'<detail custom="kept"><x:contact xmlns:x="urn:custom" callsign="X"/>'
    )
    namespaced = namespaced.replace(b"<remarks>x</remarks>", b"")
    ns_report = cot.parse_cot_xml(namespaced)
    assert ns_report["detail"]["attributes"] == {"custom": "kept"}
    assert "contact" not in ns_report["detail"]["typed"]
    assert ns_report["detail"]["elements"][0]["namespace"] == "urn:custom"


