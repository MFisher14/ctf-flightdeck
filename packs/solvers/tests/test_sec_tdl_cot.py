def test_module_is_static_offline_and_does_not_offer_active_operations():
    source = Path(cot.__file__).read_text(encoding="utf-8")
    tree = ast.parse(source)
    forbidden_imports = {
        "socket", "requests", "httpx", "urllib", "http", "ftplib", "subprocess"
    }
    imported = {
        node.names[0].name.split(".", 1)[0]
        for node in ast.walk(tree)
        if isinstance(node, ast.Import)
    } | {
        (node.module or "").split(".", 1)[0]
        for node in ast.walk(tree)
        if isinstance(node, ast.ImportFrom)
    }
    assert forbidden_imports.isdisjoint(imported)
    forbidden_calls = {"eval", "exec", "compile", "__import__", "urlopen", "extractall"}
    called_names = {
        node.func.id
        for node in ast.walk(tree)
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name)
    }
    assert forbidden_calls.isdisjoint(called_names)

