def test_deterministic_fail_closed_fuzz_and_all_truncations(tmp_path):
    rng = random.Random(0x5A2026)
    cases = [b"", b"\0", b"PK\x03\x04", b"APX\0", None, 1, "text", [], {}, memoryview(b"abc")]
    cases += [rng.randbytes(length) for length in range(1, 128)]
    valid_apx = APX_HEADER + apx_section(b"KNOWN_DATA")
    cases += [valid_apx[:length] for length in range(len(valid_apx))]
    valid_zip = archive_bytes([("BinAppli/Station.apx", valid_apx)])
    cases += [valid_zip[:length] for length in range(0, len(valid_zip), 3)]
    for data in cases:
        for function in (engine.parse_archive, engine.parse_apx):
            try:
                function(data)
            except engine.SchneiderError:
                pass
        for direction in ("request", "response"):
            try:
                engine.decode_umas(data, direction=direction)
            except engine.SchneiderError:
                pass
    for context in ([], {}, -1, 256, "34", 1.5, True):
        with pytest.raises(engine.SchneiderError):
            engine.decode_umas(b"\x5a\1\xfe", direction="response", request_function=context)
    for path in (tmp_path, tmp_path / "missing", None, 12, [], {}):
        with pytest.raises(engine.SchneiderError):
            engine.analyze_file(path)


