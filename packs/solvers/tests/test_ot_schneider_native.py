def test_umas_session_init_and_reservation():
    for frame in (b"\x5a\0\x01", b"\x5a\0\x01\0"):
        assert engine.decode_umas(frame, direction="request")["operation"] == "initialize"
    # Hand-authored response fields from Martin Part I: max-frame 1024,
    # firmware raw0x270, two opaque dwords, clientname length7.
    init = bytes.fromhex("5a00fe00047002aabbccdd1122334407") + b"ENG-PC0"
    fields = engine.decode_umas(init, direction="response", request_function=1)["fields"]
    assert fields == {"max_frame_size": 1024, "firmware_raw": 0x270,
                      "unknown1_hex": "aabbccdd", "unknown2_hex": "11223344",
                      "client_name": "ENG-PC0", "extension_hex": ""}
    reserve = bytes.fromhex("5a00103b0e000007") + b"ENG-PC0"
    fields = engine.decode_umas(reserve, direction="request")["fields"]
    assert fields["reserver_id_hex"] == "3b0e0000"
    assert fields["name_field_length"] == 7
    assert fields["client_name"] == "ENG-PC0"
    for function in (0x11, 0x12):
        assert engine.decode_umas(bytes([0x5A, 0xF8, function]), direction="request")["session"] == 248


def test_umas_error_unknown_and_response_context():
    result = engine.decode_umas(bytes.fromhex("5a01fd1234"), direction="response", request_function=0x34)
    assert result["success"] is False
    assert result["fields"] == {"error_payload_hex": "1234"}
    result = engine.decode_umas(bytes.fromhex("5a01fe030041425a"), direction="response")
    assert result["function"] is None
    assert result["fields"] == {}
    assert "no function echo" in result["limitation"]
    result = engine.decode_umas(bytes.fromhex("5a0199deadbeef"), direction="request")
    assert result["operation"] == "unknown"
    assert result["payload_hex"] == "deadbeef"
    result = engine.decode_umas(bytes.fromhex("5a01380100"), direction="request")
    assert "not verified" in result["limitation"]
    signed = b"\x5a\x01\xfe\x01" + bytes(32) + b"\x5a\x01\xfd"
    result = engine.decode_umas(signed, direction="response", request_function=0x38)
    assert "outer status only" in result["limitation"]


def test_modbus_tcp_big_endian_header_and_exact_single_frame():
    # MBAP: transaction0x1234, protocol0, length8, unit255, seven-byte PDU.
    frame = bytes.fromhex("123400000008ff5af83400010700")
    result = engine.decode_umas(frame, direction="request", framing="tcp")
    assert result["mbap"] == {"transaction_id": 0x1234, "protocol_id": 0, "length": 8, "unit_id": 255}
    assert result["fields"]["block_number"] == 7
    for bad in (frame[:-1], frame + b"\0", frame + frame,
                frame[:2] + b"\0\1" + frame[4:]):
        with pytest.raises(engine.SchneiderError):
            engine.decode_umas(bad, direction="request", framing="tcp")


