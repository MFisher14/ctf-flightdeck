# Verbatim published APX header, not generated by the engine.
APX_HEADER = bytes.fromhex(
    "41 50 58 00 00 01 02 01 10 01 10 60 f6 c3 30 00 "
    "65 92 0b 06 01 00 00 00 00 00 00 00 00 00 00 00"
)
XEF = b'''<FEFExchangeFile><fileHeader company="Schneider Electric"/>
<contentHeader name="PumpStation"/><dataBlock>
<variables name="PumpRun" typeName="BOOL" topologicalAddress="%M12"/>
</dataBlock><program><identProgram name="MAIN"/>
<STSource>PumpRun := TRUE; (* CSCTF{xef_fixture} *)</STSource>
</program></FEFExchangeFile>'''


def apx_section(payload=b"", *, kind=2, number=0x33, attributes=0):
    """Hand encoder from apxutil's published offsets, independent of engine."""
    if kind == 0:
        header = struct.pack("<HHHH", kind, 0, number, 0)
    elif kind == 1:
        header = struct.pack("<HHH", kind, 0, number) + bytes(10)
    else:
        header = struct.pack("<HHHIIH", kind, 0, number, 0x10203040, len(payload), 0)
    rte = struct.pack("<IIIHBB", 0, max(0, len(payload) - 1), attributes, 0x1234, 0x9A, 0)
    return header + rte + payload


def archive_bytes(entries, compression=zipfile.ZIP_DEFLATED):
    stream = io.BytesIO()
    with zipfile.ZipFile(stream, "w", compression=compression) as writer:
        for name, data in entries:
            writer.writestr(name, data)
    return stream.getvalue()


def test_apx_published_header_and_independent_sections():
    payload = b"\0PumpMotor\0CSCTF{apx_fixture}\0\0" + "ControlRoom".encode("utf-16le")
    data = APX_HEADER + apx_section(kind=0, number=1) + apx_section(kind=1, number=2) + apx_section(payload)
    result = engine.parse_apx(data)
    assert result["format"] == "schneider-apx"
    assert result["header"]["version_raw"] == 0x100
    assert result["header"]["rte_type"] == 2
    assert result["header"]["rte_size"] == 16
    assert result["complete"] is True
    assert [s["offset"] for s in result["sections"]] == [32, 56, 88]
    section = result["sections"][2]
    assert section["number"] == 0x33
    assert section["memory_offset_raw"] == 0x10203040
    assert section["stored_data_size"] == len(payload)
    assert section["crc_raw"] == 0x1234
    assert section["memory_byte_raw"] == 0x9A
    assert section["evidence"]["flag_candidates"] == ["CSCTF{apx_fixture}"]
    assert any(s["text"] == "ControlRoom" for s in section["evidence"]["strings"])
    assert any(s["text"] == "PumpMotor" for s in section["evidence"]["strings"])


def test_apx_compression_and_absent_data_are_inventory_only():
    data = APX_HEADER + apx_section(b"NOT_A_ZLIB_STREAM", attributes=1 << 13)
    assert engine.parse_apx(data)["sections"][0]["compressed"] is True
    # apxutil's observed attribute28 suppresses stored data despite header size.
    section = bytearray(apx_section(attributes=1 << 28))
    struct.pack_into("<I", section, 10, 0xFFFFFFFF)
    result = engine.parse_apx(APX_HEADER + section)
    assert result["sections"][0]["stored_data_size"] == 0
    assert result["sections"][0]["declared_data_size"] == 0xFFFFFFFF


def test_apx_unknown_layout_explicitly_partial():
    result = engine.parse_apx(APX_HEADER + b"\x03\x00OPAQUE")
    assert result["complete"] is False
    assert result["opaque_offset"] == 32
    other_rte = bytearray(APX_HEADER)
    other_rte[6] = 1
    result = engine.parse_apx(other_rte + b"VENDOR_DATA")
    assert result["complete"] is False
    assert "RTE" in result["unsupported"]


def test_sta_zip_member_inventory_and_no_extraction(tmp_path):
    data = archive_bytes([
        ("BinAppli/", b""),
        ("BinAppli/Station.apx", APX_HEADER + apx_section(b"PumpRun")),
        ("Station.apd", b"\x00\x01opaque integrity sidecar"),
    ])
    path = tmp_path / "fixture.sta"
    path.write_bytes(data)
    result = engine.analyze_file(path)
    assert result["container_hint"] == "sta"
    assert [e["kind"] for e in result["entries"]] == ["directory", "apx", "opaque"]
    assert result["entries"][1]["decoded"]["sections"][0]["number"] == 0x33
    assert list(tmp_path.iterdir()) == [path]


