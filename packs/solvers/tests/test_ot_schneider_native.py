def test_zip_duplicate_symlink_crc_dtd_and_budgets(monkeypatch):
    with pytest.raises(engine.SchneiderError, match="duplicate"):
        engine.parse_archive(archive_bytes([("a", b"1"), ("A", b"2")]))
    link = zipfile.ZipInfo("link")
    link.create_system = 3
    link.external_attr = (stat.S_IFLNK | 0o777) << 16
    with pytest.raises(engine.SchneiderError, match="symlink"):
        engine.parse_archive(archive_bytes([(link, b"target")]))
    corrupt = bytearray(archive_bytes([("data.bin", b"MATCH_ME")], zipfile.ZIP_STORED))
    corrupt[corrupt.index(b"MATCH_ME")] ^= 1
    with pytest.raises(engine.SchneiderError):
        engine.parse_archive(corrupt)
    with pytest.raises(engine.SchneiderError):
        engine.parse_archive(archive_bytes([("unitpro.xef", b'<!DOCTYPE FEFExchangeFile><FEFExchangeFile/>')]))
    monkeypatch.setattr(engine, "MAX_MEMBER", 16)
    with pytest.raises(engine.SchneiderError, match="size limit"):
        engine.parse_archive(archive_bytes([("big", b"A" * 1024)]))
    monkeypatch.setattr(engine, "MAX_ENTRIES", 1)
    with pytest.raises(engine.SchneiderError, match="directory"):
        engine.parse_archive(archive_bytes([("a", b"1"), ("b", b"2")]))


def test_zip_encrypted_inventory_without_password_request():
    data = bytearray(archive_bytes([("opaque", b"data")], zipfile.ZIP_STORED))
    # Mark an independent ordinary ZIP encrypted: it must not attempt a read.
    struct.pack_into("<H", data, 6, 1)
    cd = data.index(b"PK\x01\x02")
    struct.pack_into("<H", data, cd + 8, 1)
    result = engine.parse_archive(data)
    assert result["entries"][0]["reason"] == "encrypted member"


def test_zip_preflight_checks_actual_count_and_member_disk_before_allocation(monkeypatch):
    data = archive_bytes([("a", b"1"), ("b", b"2")])
    end = data.rindex(b"PK\x05\x06")
    cd = data.index(b"PK\x01\x02")
    variants = []
    lying_count = bytearray(data)
    struct.pack_into("<HH", lying_count, end + 8, 1, 1)
    variants.append(lying_count)
    split_member = bytearray(data)
    struct.pack_into("<H", split_member, cd + 34, 1)
    variants.append(split_member)
    zip64_member = bytearray(data)
    struct.pack_into("<I", zip64_member, cd + 24, 0xFFFFFFFF)
    variants.append(zip64_member)

    def must_not_allocate(*args, **kwargs):
        pytest.fail("invalid directory reached ZipFile allocation")

    monkeypatch.setattr(engine.zipfile, "ZipFile", must_not_allocate)
    for variant in variants:
        with pytest.raises(engine.SchneiderError):
            engine.parse_archive(variant)


