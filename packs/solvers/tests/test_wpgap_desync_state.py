def test_rfc_head_semantics_and_portswigger_range_gadget_are_kept_distinct():
    head = request(
        "head", "HEAD /docs/ HTTP/1.1\r\nHost: example.test\r\n"
        "Range: bytes=1-650\r\n\r\n",
        framing="zero", body_bytes_seen=0,
    )
    headers_only = response(
        "partial", "head", "HTTP/1.1 206 Partial Content\r\n"
        "Content-Range: bytes 1-650/1000\r\nContent-Length: 650\r\n\r\n",
    )
    ids = finding_ids(bundle(requests=[head], responses=[headers_only]))
    assert "range-head-length-gadget" in ids
    assert "head-response-overread" not in ids  # HEAD may legally advertise CL.

    nested = dict(headers_only)
    nested["raw"] += "HTTP/1.1 400 Bad Request\r\nContent-Length: 0\r\n\r\n"
    outer = request(
        "outer", "GET /docs/index.html HTTP/1.1\r\nHost: example.test\r\n\r\n",
        hop="edge", connection="front-1", framing="zero",
    )
    ids = finding_ids(bundle(
        requests=[outer, head], responses=[nested], links=[rewrite("outer", "head")],
    ))
    assert {"range-head-length-gadget", "head-response-overread"} <= ids


def test_envoy_advisory_h3_to_h1_body_debt_high_signal_sequence():
    # GHSA-8phg-2h2q-jgxf: H3 HEADERS+FIN, CL=51, no DATA; Envoy preserved
    # CL into H1, /early responded, and 51 bytes of /allowed paid body debt.
    h3 = (
        ":method: GET\n:path: /early\n:scheme: https\n:authority: edge.test\n"
        "content-length: 51\n\n"
    )
    upstream = (
        "GET /early HTTP/1.1\r\nhost: localhost\r\nContent-Length: 51\r\n\r\n"
    )
    next_request = (
        "GET /allowed HTTP/1.1\r\nhost: localhost\r\n"
        "x-smuggle: GET /pwn HTTP/1.1\r\nhost: localhost\r\n\r\n"
    )
    assert next_request[:51].endswith("x-smuggle: ")
    assert next_request[51:].startswith("GET /pwn HTTP/1.1")
    evidence = bundle(
        requests=[
            request("h3-early", h3, hop="edge", connection="quic-1", protocol="h3",
                    framing="stream", body_bytes_seen=0, end_stream=True),
            request("h1-early", upstream, hop="upstream", protocol="h1",
                    framing="content-length", body_bytes_seen=0, end_stream=True),
            request("h1-allowed", next_request, sequence=2, hop="upstream", protocol="h1",
                    framing="zero", end_stream=True),
        ],
        responses=[response(
            "early-ok", "h1-early", "HTTP/1.1 200 OK\r\nContent-Length: 8\r\n\r\nEARLY-OK",
            before_body_complete=True, connection_reused=True,
        )],
        links=[
            rewrite("h3-early", "h1-early"),
            {"kind": "consumed-as-body", "from": "h1-allowed", "to": "h1-early", "bytes": 51},
        ],
        config={"downstream_protocol": "h3", "upstream_protocol": "h1",
                "reuse_upstream": True},
    )
    ids = finding_ids(evidence)
    assert {"h3-length-mismatch-at-fin", "h3-h1-body-debt",
            "early-final-response", "early-response-reuse"} <= ids

    no_consumption = dict(evidence)
    no_consumption["links"] = [rewrite("h3-early", "h1-early")]
    ids = finding_ids(no_consumption)
    assert "h3-length-mismatch-at-fin" in ids
    assert "h3-h1-body-debt" not in ids

    wrong_debt = dict(evidence)
    wrong_debt["links"] = [
        rewrite("h3-early", "h1-early"),
        {"kind": "consumed-as-body", "from": "h1-allowed", "to": "h1-early", "bytes": 50},
    ]
    assert "h3-h1-body-debt" not in finding_ids(wrong_debt)


def test_double_desync_requires_both_orientations_same_pool_and_consumption_link():
    first = "GET /con HTTP/1.1\r\nHost: x.test\r\nContent-Length: 7\r\n\r\n"
    second = "POST / HTTP/1.1\r\nHost: x.test\r\nContent-Length: 8\r\n\r\nABCDEFGH"
    victim = "GET /victim HTTP/1.1\r\nHost: x.test\r\n\r\n"
    evidence = bundle(
        requests=[
            request("a-edge", first, sequence=1, hop="edge", connection="front-a",
                    framing="zero", body_bytes_seen=0),
            request("a-back", first, sequence=1, framing="content-length", body_bytes_seen=0),
            request("b-edge", second, sequence=2, hop="edge", connection="front-b",
                    framing="content-length", body_bytes_seen=8),
            request("b-back", second, sequence=2, framing="zero", body_bytes_seen=0),
            request("victim", victim, sequence=3, framing="zero", body_bytes_seen=0),
        ],
        responses=[response(
            "a-response", "a-back", "HTTP/1.1 200 OK\r\nContent-Length: 0\r\n\r\n",
            before_body_complete=True, connection_reused=True,
        )],
        links=[
            rewrite("a-edge", "a-back"), rewrite("b-edge", "b-back"),
            {"kind": "consumed-as-body", "from": "b-back", "to": "a-back", "bytes": 7},
            {"kind": "prefix-contaminates", "from": "b-back", "to": "victim"},
        ],
        config={"reuse_upstream": True},
    )
    assert "double-desync-sequence" in finding_ids(evidence)

    missing_link = dict(evidence)
    missing_link["links"] = [
        rewrite("a-edge", "a-back"), rewrite("b-edge", "b-back"),
        {"kind": "consumed-as-body", "from": "b-back", "to": "a-back", "bytes": 7},
    ]
    assert "double-desync-sequence" not in finding_ids(missing_link)


