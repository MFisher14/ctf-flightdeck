def test_original_te_zero_dechunk_shape_and_safe_reframing_control():
    # Bugcrowd's published TE.0 PoC is chunked OPTIONS with a request in the
    # decoded bytes.  The saved upstream view below has dechunked but omitted CL.
    ingress = (
        "OPTIONS / HTTP/1.1\r\nHost: bank.test\r\nTransfer-Encoding: chunked\r\n\r\n"
        "2b\r\nGET /smuggled HTTP/1.1\r\nHost: bank.test\r\n\r\n\r\n0\r\n\r\n"
    )
    decoded = (
        "OPTIONS / HTTP/1.1\r\nHost: bank.test\r\n\r\n"
        "GET /smuggled HTTP/1.1\r\nHost: bank.test\r\n\r\n"
    )
    vulnerable = bundle(
        requests=[
            request("te-front", ingress, hop="edge", connection="front-1",
                    framing="transfer-encoding"),
            request("te-back", decoded, framing="zero"),
        ],
        links=[rewrite("te-front", "te-back")],
        config={"dechunk_requests": True, "reuse_upstream": True},
    )
    assert "te-zero-after-dechunk" in finding_ids(vulnerable)

    safe_back = decoded.replace("Host: bank.test\r\n\r\n", "Host: bank.test\r\nContent-Length: 43\r\n\r\n", 1)
    safe = bundle(
        requests=[
            request("te-front", ingress, hop="edge", connection="front-1",
                    framing="transfer-encoding"),
            request("te-back", safe_back, framing="content-length"),
        ],
        links=[rewrite("te-front", "te-back")],
        config={"dechunk_requests": True, "reuse_upstream": True},
    )
    assert "te-zero-after-dechunk" not in finding_ids(safe)

    invalid_chunking = bundle(
        requests=[
            request("te-front", ingress.replace("2b\r\n", "2f\r\n", 1),
                    hop="edge", connection="front-1", framing="transfer-encoding"),
            request("te-back", decoded, framing="zero"),
        ],
        links=[rewrite("te-front", "te-back")],
        config={"dechunk_requests": True, "reuse_upstream": True},
    )
    assert "te-zero-after-dechunk" not in finding_ids(invalid_chunking)


