def test_nested_validation_fails_closed_without_stdlib_exception_leaks():
    valid = bundle(requests=[request(
        "r", "GET / HTTP/1.1\r\nHost: x.test\r\n\r\n",
    )])
    cases = []

    unknown = json.loads(json.dumps(valid))
    unknown["requests"][0]["mystery"] = True
    cases.append(unknown)

    bool_as_int = json.loads(json.dumps(valid))
    bool_as_int["requests"][0]["body_bytes_seen"] = True
    cases.append(bool_as_int)

    invalid_raw = json.loads(json.dumps(valid))
    invalid_raw["requests"][0]["raw"] = "GET /missing-version\r\n\r\n"
    cases.append(invalid_raw)

    bad_response = json.loads(json.dumps(valid))
    bad_response["responses"] = [{
        "id": "resp", "request_id": "r", "connection": "pool-1",
        "raw": "NOT HTTP\r\n\r\n",
    }]
    cases.append(bad_response)

    missing_kind = json.loads(json.dumps(valid))
    missing_kind["links"] = [{"from": "r", "to": "r"}]
    cases.append(missing_kind)

    unknown_target = json.loads(json.dumps(valid))
    unknown_target["links"] = [{"kind": "rewritten-from", "from": "r", "to": "absent"}]
    cases.append(unknown_target)

    mismatched_connection = json.loads(json.dumps(valid))
    mismatched_connection["responses"] = [{
        "id": "resp", "request_id": "r", "connection": "other-pool",
        "raw": "HTTP/1.1 200 OK\r\nContent-Length: 0\r\n\r\n",
    }]
    cases.append(mismatched_connection)

    for case in cases:
        with pytest.raises(state.DesyncEvidenceError):
            state.report_dict(case)

    oversized_mapping = bundle(requests=[
        request("large-1", "POST / HTTP/1.1\r\nHost: x\r\n\r\n" + "A" * 1_100_000),
        request("large-2", "POST / HTTP/1.1\r\nHost: x\r\n\r\n" + "B" * 1_100_000),
    ])
    with pytest.raises(state.DesyncEvidenceError, match="aggregate raw evidence"):
        state.report_dict(oversized_mapping)


def test_report_cli_argparse_guard_and_static_offline_surface(tmp_path, capsys):
    evidence = bundle(requests=[request(
        "r", "GET / HTTP/1.1\r\nHost: x.test\r\n\r\n",
    )])
    path = tmp_path / "evidence.json"
    path.write_text(json.dumps(evidence), encoding="utf-8")
    assert state.main([str(path), "--pretty"]) == 0
    report = json.loads(capsys.readouterr().out)
    assert report["offline"] is True and report["network_requests"] == 0
    assert report["summary"] == {
        "finding_count": 0, "links": 0, "request_records": 1, "response_records": 0,
    }

    assert state.main(["--definitely-not-an-option"]) == 2
    assert "Traceback" not in capsys.readouterr().err
    assert state.main([str(tmp_path / "missing.json")]) == 2
    assert "Traceback" not in capsys.readouterr().err
    assert state.main(["bad\x00path"]) == 2
    assert "Traceback" not in capsys.readouterr().err
    assert state.main(["\ud800"]) == 2
    assert "Traceback" not in capsys.readouterr().err
    assert state.main([None]) == 2
    assert "Traceback" not in capsys.readouterr().err

    tree = ast.parse(ENGINE.read_text(encoding="utf-8"))
    imported = set()
    called_names = set()
    called_attributes = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported.update(alias.name.split(".", 1)[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported.add(node.module.split(".", 1)[0])
        elif isinstance(node, ast.Call):
            if isinstance(node.func, ast.Name):
                called_names.add(node.func.id)
            elif isinstance(node.func, ast.Attribute):
                called_attributes.add(node.func.attr)
    assert not ({"socket", "requests", "urllib", "httpx", "subprocess"} & imported)
    assert not ({"eval", "exec", "compile"} & called_names)
    assert not ({"system", "popen", "urlopen"} & called_attributes)

