def _only_declared(call, declared) -> None:
    """A clean return is allowed; hostile input may raise only ``declared``."""

    try:
        call()
    except declared:
        return


def _mutations(valid: bytes, oversized: bytes) -> tuple[bytes, ...]:
    generator = random.Random(0xDB57)
    random_bytes = bytes(generator.randrange(256) for _ in range(97))
    truncated = valid[:-1]
    flipped = bytearray(valid)
    flipped[max(0, len(flipped) // 2)] ^= 0x80
    return b"", random_bytes, truncated, bytes(flipped), oversized


# ---- SAML lexical / canonicalization -------------------------------------------------


def test_saml_vector_lock_canonical_xml_attribute_order_and_digest() -> None:
    # Canonical XML 1.0 sorts namespace declarations before attributes, then
    # unqualified attributes before namespace-qualified attributes.
    source = '<r xmlns:z="urn:z" z:b="2" a="1"></r>'
    canonical = b'<r xmlns:z="urn:z" a="1" z:b="2"></r>'
    report = saml.lint_saml_xml(source)
    inclusive = next(
        item for item in report.probes
        if item.mode == "inclusive" and item.with_comments is False
    )

    assert inclusive.status == "ok"
    assert inclusive.output_bytes == len(canonical)
    assert inclusive.sha256 == hashlib.sha256(canonical).hexdigest()
    assert inclusive.semantic_roundtrip is True
    assert inclusive.idempotent is True
    serialized = saml.report_to_dict(report)
    assert serialized["network_requests"] == 0
    assert serialized["signature_verification_performed"] is False


def test_saml_fail_closed_fuzz_all_public_boundaries(monkeypatch) -> None:
    valid = b'<r xmlns:z="urn:z" z:b="2" a="1"></r>'
    monkeypatch.setattr(saml, "MAX_XML_BYTES", 128)
    cases = _mutations(valid, b"<r>" + b"A" * 129 + b"</r>")
    for value in cases:
        _only_declared(lambda value=value: saml.lint_saml_xml(value), saml.WpgapSamlError)

    valid_report = saml.lint_saml_xml("<r/>")
    assert saml.report_to_dict(valid_report)["xml_bytes"] == 4
    for value in (None, b"", {}, object(), valid_report.findings):
        _only_declared(lambda value=value: saml.report_to_dict(value), saml.WpgapSamlError)

    for argv in ([], ["--not-an-option"], [None], ["\ud800"]):
        result = saml.main(argv)
        assert isinstance(result, int) and result in (0, 2)


# ---- OAuth/OIDC policy ---------------------------------------------------------------


def _oauth_redirect_document() -> dict[str, object]:
    return {
        "schema_version": 1,
        "policy": {},
        "flows": [
            {
                "id": "method-preserved",
                "redirect": {
                    "incoming_method": "POST",
                    "credentials_in_body": True,
                    "status": 307,
                    "target_role": "client",
                },
            },
            {
                "id": "see-other",
                "redirect": {
                    "incoming_method": "POST",
                    "credentials_in_body": True,
                    "status": 303,
                    "target_role": "client",
                },
            },
        ],
    }


def test_oauth_vector_lock_rfc9110_method_preservation_and_rfc9700_policy() -> None:
    # RFC 9110 defines 307 as method preserving while 303 changes the follow-up
    # to retrieval semantics; RFC 9700 therefore forbids credential POSTs via 307.
    document = _oauth_redirect_document()
    report = oauth.analyze_json(json.dumps(document, separators=(",", ":")))
    forwarding = [
        item for item in report.findings
        if item.code == "credential_post_307_forwarding"
    ]

    assert len(forwarding) == 1
    assert forwarding[0].severity == "critical"
    assert forwarding[0].flow_ids == ("method-preserved",)
    assert not any(
        item.code.startswith("credential_post_") and "see-other" in item.flow_ids
        for item in report.findings
    )
    assert report.offline is True and report.network_requests == 0


def test_oauth_fail_closed_fuzz_all_public_boundaries(monkeypatch) -> None:
    valid_object = _oauth_redirect_document()
    valid = json.dumps(valid_object, separators=(",", ":")).encode()
    monkeypatch.setattr(oauth, "MAX_INPUT_BYTES", 256)
    cases = _mutations(valid, b"{" + b"A" * 257 + b"}")
    for value in cases:
        _only_declared(lambda value=value: oauth.load_evidence(value), oauth.WPGAPOAuthPolicyError)
        _only_declared(lambda value=value: oauth.analyze_json(value), oauth.WPGAPOAuthPolicyError)

    mapping_cases = (
        {},
        None,
        [],
        {"schema_version": 1, "policy": {}, "flows": []},
        {"schema_version": 1, "policy": {}, "flows": [{"id": "x\x00"}]},
        {"schema_version": 1, "policy": {"unknown": True}, "flows": [{"id": "x"}]},
        valid_object,
    )
    for value in mapping_cases:
        _only_declared(lambda value=value: oauth.analyze_policy(value), oauth.WPGAPOAuthPolicyError)

    for argv in ([], ["--not-an-option"], ["\ud800"]):
        result = oauth.main(argv)
        assert isinstance(result, int) and result in (0, 2)


def test_oauth_cli_none_path_is_fail_closed() -> None:
    result = oauth.main([None])
    assert isinstance(result, int) and result == 2


# ---- Apache/Nginx configuration and Windows best-fit --------------------------------


def test_webconf_vector_lock_published_worstfit_and_server_config_shapes() -> None:
    # Microsoft's CP1252 best-fit rows used in Orange Tsai's published example.
    report = webconf.analyze_best_fit("√π⁷≤∞", "cp1252")
    assert report.projected_text == "vp7=8"
    assert report.complete is True
    assert [item.replacement for item in report.mappings] == ["v", "p", "7", "=", "8"]

    cp932 = {(item.source, item.replacement) for item in webconf.best_fit_table("cp932")}
    assert ("¥", "\\") in cp932
    assert ("\u00ad", "-") in cp932
    assert ("／", "/") not in cp932

    nginx = webconf.analyze_server_config(
        "server { location /static/ { "
        "return 302 http://172.17.0.1$uri; } }",
        server="nginx",
    )
    assert "nginx-decoded-uri-response-field" in {
        item.code for item in nginx.findings
    }

    apache = webconf.analyze_server_config(
        'RewriteRule "^/user/(.+)$" "/var/user/$1/profile.yml"',
        server="apache",
    )
    assert "apache-encoded-question-suffix" in {
        item.code for item in apache.findings
    }


def test_webconf_fail_closed_fuzz_all_public_boundaries(monkeypatch) -> None:
    valid_config = b"server { location / { return 200 ok; } }"
    monkeypatch.setattr(webconf, "MAX_INPUT_BYTES", 128)
    config_cases = _mutations(
        valid_config,
        b"server { # " + b"A" * 129 + b"\n}",
    )
    for value in config_cases:
        _only_declared(
            lambda value=value: webconf.analyze_server_config(value, server="nginx"),
            webconf.WPGAPWebConfError,
        )

    monkeypatch.setattr(webconf, "MAX_BEST_FIT_CHARS", 16)
    text_generator = random.Random(0xB357)
    random_text = "".join(chr(0x80 + text_generator.randrange(0x700)) for _ in range(9))
    text_cases = (
        "",
        random_text,
        "√π⁷≤",
        "√π⁷≤∞"[:-1],
        "√π⁷≠∞",
        "A" * 17,
        b"not-text",
        "\ud800",
    )
    for value in text_cases:
        _only_declared(
            lambda value=value: webconf.analyze_best_fit(value, "cp1252"),
            webconf.WPGAPWebConfError,
        )

    for selector in (None, "cp1252", "", "cp437", object(), 10**5000):
        _only_declared(
            lambda selector=selector: webconf.best_fit_table(selector),
            webconf.WPGAPWebConfError,
        )

    for argv in ([], [None], ["\ud800"], ["--not-an-option"], ["bestfit", "∞", "--code-page", "cp1252"]):
        result = webconf.main(argv)
        assert isinstance(result, int) and result in (0, 2)


# ---- Dependency-source precedence ---------------------------------------------------


def _depconf_package(report: dict[str, object], ecosystem: str, name: str) -> dict[str, object]:
    rows = [
        item for item in report["packages"]
        if item["ecosystem"] == ecosystem and item["name"] == name
    ]
    assert len(rows) == 1
    return rows[0]


def test_depconf_vector_lock_pip_pools_all_configured_indexes() -> None:
    # pip documents that index-url and extra-index-url form one candidate pool;
    # declaration order is not source priority. PEP 503 normalizes _ and . to -.
    report = depconf.audit_configs(
        {
            "pip.conf": (
                "[global]\n"
                "index-url = https://packages.corp.example/simple\n"
                "extra-index-url = https://pypi.org/simple\n"
            ),
            "requirements.txt": "Acme_Core==1.2.3\n",
        },
        internal_names={"pip": ["acme.core"]},
        internal_hosts=["packages.corp.example"],
    )
    package = _depconf_package(report, "pip", "acme-core")

    assert package["outcome"] == "shadowable"
    assert {item["role"] for item in package["sources"]} == {"internal", "public"}
    assert report["offline"] is True and report["network_requests"] == 0


def test_depconf_fail_closed_fuzz_all_public_boundaries(tmp_path, monkeypatch) -> None:
    valid = b"[global]\nindex-url=https://pypi.org/simple\n"
    generator = random.Random(0xD3C0)
    random_bytes = bytes(generator.randrange(256) for _ in range(83))
    monkeypatch.setattr(depconf, "MAX_FILE", 128)
    file_values = (b"", random_bytes, valid[:-1], valid[:10] + b"\xff" + valid[11:], b"A" * 129)
    for value in file_values:
        _only_declared(
            lambda value=value: depconf.audit_configs(
                {"pip.conf": value}, internal_names={"pip": ["acme-core"]}
            ),
            depconf.DepConfError,
        )

    valid_path = tmp_path / "pip.conf"
    valid_path.write_bytes(valid)
    random_path = tmp_path / "random.conf"
    random_path.write_bytes(random_bytes)
    truncated_path = tmp_path / "truncated.conf"
    truncated_path.write_bytes(valid[:-1])
    flipped_path = tmp_path / "flipped.conf"
    flipped_path.write_bytes(valid[:10] + b"\xff" + valid[11:])
    oversized_path = tmp_path / "oversized.conf"
    oversized_path.write_bytes(b"A" * 129)
    for paths in (
        [valid_path],
        [random_path],
        [truncated_path],
        [flipped_path],
        [oversized_path],
        [],
        [None],
    ):
        _only_declared(
            lambda paths=paths: depconf.audit_paths(
                paths, internal_names={"pip": ["acme-core"]}
            ),
            depconf.DepConfError,
        )

    for argv in ([], ["--not-an-option"], [None], [str(valid_path)]):
        result = depconf.main(argv)
        assert isinstance(result, int) and result in (0, 2)


# ---- Modern HTTP desynchronization state --------------------------------------------


def _desync_bundle() -> dict[str, object]:
    return {
        "schema": "wpgap-desync-evidence-v1",
        "requests": [
            {
                "id": "request-1",
                "sequence": 1,
                "hop": "upstream",
                "connection": "pool-1",
                "protocol": "h1",
                "framing": "zero",
                "body_bytes_seen": 0,
                "end_stream": True,
                "raw": "GET / HTTP/1.1\r\nHost: example.test\r\n\r\n",
            }
        ],
        "responses": [
            {
                "id": "response-1",
                "request_id": "request-1",
                "connection": "pool-1",
                "raw": "HTTP/1.1 204 No Content\r\n\r\nSURPLUS",
                "before_body_complete": False,
                "connection_reused": False,
            }
        ],
        "links": [],
        "config": {},
    }


def test_desync_vector_lock_rfc9110_204_response_has_no_content() -> None:
    # RFC 9110 defines 204 as terminating after the header section. Bytes after
    # it are surplus parser state, independent of a Content-Length header.
    evidence = _desync_bundle()
    findings = desync.analyze_evidence(evidence)
    overread = [
        item for item in findings if item.finding_id == "bodyless-response-overread"
    ]

    assert len(overread) == 1
    assert overread[0].request_ids == ("request-1",)
    report = desync.report_dict(evidence)
    assert report["summary"] == {
        "request_records": 1,
        "response_records": 1,
        "links": 0,
        "finding_count": len(findings),
    }
    assert report["offline"] is True and report["network_requests"] == 0


def test_desync_fail_closed_fuzz_all_public_boundaries(monkeypatch) -> None:
    valid = json.dumps(_desync_bundle(), separators=(",", ":")).encode()
    monkeypatch.setattr(desync, "MAX_INPUT_BYTES", 512)
    cases = _mutations(valid, b"{" + b"A" * 513 + b"}")
    mapping_cases = (
        {},
        [],
        None,
        {"schema": desync.SCHEMA, "requests": []},
        _desync_bundle(),
    )
    for entrypoint in (desync.analyze_evidence, desync.report_dict):
        for value in (*cases, *mapping_cases):
            _only_declared(
                lambda value=value, entrypoint=entrypoint: entrypoint(value),
                desync.DesyncEvidenceError,
            )

    for argv in ([], ["--not-an-option"], [None], ["\ud800"]):
        result = desync.main(argv)
        assert isinstance(result, int) and result in (0, 2)

