def _artifact_corpus():
    rng = random.Random(0x53535449)
    rendered = DOCUMENTED_RENDERS["jinja2"].encode()
    truncated = rendered[:-1]
    flipped = bytearray(rendered)
    flipped[len(flipped) // 2] ^= 1
    return [b"", "", bytearray(), b"\xff" * 128, rng.randbytes(257),
            rendered[:8], truncated, bytes(flipped), "\udcff\x00{{truncated"]


@pytest.mark.parametrize("entrypoint", [engines.detect, engines.analyze])
def test_primary_analyze_detect_entrypoints_fail_closed_on_artifact_fuzz(entrypoint):
    for specimen in _artifact_corpus():
        try:
            result = entrypoint(specimen, marker=MARKER)
        except Exception as exc:  # pragma: no cover - assertion identifies leaked class
            pytest.fail(f"{entrypoint.__name__} leaked {type(exc).__name__}: {exc}")
        assert isinstance(result, tuple if entrypoint is engines.detect else dict)


@pytest.mark.parametrize("entrypoint", [helper.detect_response, helper.analyze_response])
def test_legacy_analyze_detect_entrypoints_fail_closed_on_artifact_fuzz(entrypoint):
    for specimen in _artifact_corpus() + [b"A" * (1 << 20)]:
        try:
            result = entrypoint(specimen)
        except Exception as exc:  # pragma: no cover - assertion identifies leaked class
            pytest.fail(f"{entrypoint.__name__} leaked {type(exc).__name__}: {exc}")
        assert isinstance(result, list if entrypoint is helper.detect_response else dict)


@pytest.mark.parametrize("entrypoint", [engines.detect, engines.analyze])
def test_primary_oversize_boundary_raises_only_explicit_validation_error(entrypoint, monkeypatch):
    monkeypatch.setattr(engines, "MAX_SAVED_BYTES", 128)
    with pytest.raises(ValueError) as caught:
        entrypoint(b"A" * 129, marker=MARKER)
    assert type(caught.value) is ValueError
    assert "saved_response exceeds 128 bytes" in str(caught.value)


def test_truncated_and_bit_flipped_results_never_become_render_proof():
    marker = DOCUMENTED_RENDERS["jinja2"]
    changed = marker[:10] + ("X" if marker[10] != "X" else "Y") + marker[11:]
    for specimen in (marker[:-1], changed):
        assert not any(row.confidence == "high" for row in engines.detect(specimen, marker=MARKER))
        assert not any(row["confidence"] == "high" for row in helper.detect_response(specimen))
