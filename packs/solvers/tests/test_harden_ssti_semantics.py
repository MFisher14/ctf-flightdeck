"""Independent semantic locks and fail-closed fuzz for the SSTI analyzers.

Expected templates/results are transcribed from the template engines' own
language documentation, rather than generated by either engine under test:

* Jinja: https://jinja.palletsprojects.com/en/stable/templates/#math
* Twig: https://twig.symfony.com/doc/3.x/templates.html#expressions
* FreeMarker: https://freemarker.apache.org/docs/ref_builtins_string.html
* Velocity: https://velocity.apache.org/engine/2.4.1/vtl-reference.html
* ERB: https://ruby-doc.org/stdlib/libdoc/erb/rdoc/ERB.html
* Smarty: https://github.com/smarty-php/smarty/blob/master/src/Parser/TemplateParser.y
* Handlebars: https://handlebarsjs.com/guide/builtin-helpers.html#if
* Pug: https://pugjs.org/language/interpolation.html
* Mako: https://docs.makotemplates.org/en/latest/syntax.html

Jinja2 and Mako are additionally checked against their installed reference
libraries. No test performs a request or executes an exploit payload.
"""
from __future__ import annotations

import random

from jinja2 import Environment
from mako.template import Template as MakoTemplate
import pytest

import ssti_engines as engines
import ssti_helper as helper


MARKER = "LOCK_SSTI"

# The wrapper index is part of the public probe protocol. Pug differs because a
# text interpolation at the beginning of a source line requires the ``|`` text
# marker; otherwise the leading wrapper is parsed as a tag declaration.
DOCUMENTED_RAW_PROBES = {
    "jinja2": "LOCK_SSTI_01_A{{7*'7'}}LOCK_SSTI_01_Z",
    "twig": "LOCK_SSTI_01_A{{7*'7'}}LOCK_SSTI_01_Z",
    "freemarker": 'LOCK_SSTI_02_A${"r5d"?upper_case}LOCK_SSTI_02_Z',
    "velocity": "LOCK_SSTI_03_A#set($r5d_probe = 7 * 7)${r5d_probe}LOCK_SSTI_03_Z",
    "erb": "LOCK_SSTI_04_A<%= 7 * 7 %>LOCK_SSTI_04_Z",
    "smarty": "LOCK_SSTI_05_A{7 * 7}LOCK_SSTI_05_Z",
    "handlebars": "LOCK_SSTI_06_A{{#if true}}R5D_OK{{/if}}LOCK_SSTI_06_Z",
    "pug": "| LOCK_SSTI_07_A#{7 * 7}LOCK_SSTI_07_Z",
    "mako": 'LOCK_SSTI_08_A${"r5d".upper()}LOCK_SSTI_08_Z',
}

DOCUMENTED_RENDERS = {
    "jinja2": "LOCK_SSTI_01_A7777777LOCK_SSTI_01_Z",
    "twig": "LOCK_SSTI_01_A49LOCK_SSTI_01_Z",
    "freemarker": "LOCK_SSTI_02_AR5DLOCK_SSTI_02_Z",
    "velocity": "LOCK_SSTI_03_A49LOCK_SSTI_03_Z",
    "erb": "LOCK_SSTI_04_A49LOCK_SSTI_04_Z",
    "smarty": "LOCK_SSTI_05_A49LOCK_SSTI_05_Z",
    "handlebars": "LOCK_SSTI_06_AR5D_OKLOCK_SSTI_06_Z",
    "pug": "LOCK_SSTI_07_A49LOCK_SSTI_07_Z",
    "mako": "LOCK_SSTI_08_AR5DLOCK_SSTI_08_Z",
}


@pytest.mark.parametrize("engine", [name for name in engines.ENGINES if name != "pug"])
def test_engine_catalog_matches_documented_template_semantics(engine):
    variant = engines.build_payloads(engine, contexts="raw", marker=MARKER)[0]
    assert variant.raw_payload == DOCUMENTED_RAW_PROBES[engine]
    assert variant.expected_render == DOCUMENTED_RENDERS[engine]


def test_pug_raw_probe_uses_documented_buffered_text_syntax():
    variant = engines.build_payloads("pug", contexts="raw", marker=MARKER)[0]
    assert variant.raw_payload == DOCUMENTED_RAW_PROBES["pug"]


def test_installed_reference_libraries_confirm_python_template_results():
    assert Environment().from_string("{{7*'7'}}").render() == "7777777"
    assert MakoTemplate('${"r5d".upper()}').render() == "R5D"


@pytest.mark.parametrize("engine", engines.ENGINES)
def test_exact_documented_render_is_classified_without_engine_output_oracle(engine):
    found = engines.detect(DOCUMENTED_RENDERS[engine], marker=MARKER)
    assert [(row.engine, row.score, row.confidence) for row in found] == [
        (engine, 100, "high")
    ]


