_PLAN_NAME_TOKENS = {"planner", "plans", "builder", "builders"}
_ENTRY_PREF = ("solve", "run", "main", "analyze", "analyse", "decode", "recover", "attack", "scan",
               "extract", "parse", "identify", "detect")
_EXT_RE = re.compile(r"^\.[A-Za-z0-9]{1,8}$")


@dataclass
class Facts:
    path: Path
    docstring: str = ""
    has_main: bool = False
    defs: list[str] = field(default_factory=list)
    classes: list[str] = field(default_factory=list)
    imports: set[str] = field(default_factory=set)       # unconditional module-level top names
    which: set[str] = field(default_factory=set)
    subprocess_tools: set[str] = field(default_factory=set)
    exts: set[str] = field(default_factory=set)
    magics: set[str] = field(default_factory=set)
    flag_scan: bool = False
    lines: int = 0
    syntax_error: str | None = None


def _is_main_guard(node) -> bool:
    t = node.test if isinstance(node, ast.If) else None
    return (isinstance(t, ast.Compare) and isinstance(t.left, ast.Name) and t.left.id == "__name__"
            and any(isinstance(c, ast.Constant) and c.value == "__main__" for c in t.comparators))


def _module_level(body):
    """Module-level statements, descending into top-level if/try/with blocks (a guarded `main`
    or `if __name__ == "__main__"` nested under `if not _shadowed:` still counts)."""
    for node in body:
        yield node
        if isinstance(node, ast.If) and not _is_main_guard(node):
            yield from _module_level(node.body)
            yield from _module_level(node.orelse)
        elif isinstance(node, ast.Try):
            for part in (node.body, node.orelse, node.finalbody, *(h.body for h in node.handlers)):
                yield from _module_level(part)
        elif isinstance(node, ast.With):
            yield from _module_level(node.body)


def _strs(node) -> list[str]:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return [node.value]
    if isinstance(node, (ast.Tuple, ast.List, ast.Set)):
        return [e.value for e in node.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)]
    return []


def _bytes(node) -> list[bytes]:
    if isinstance(node, ast.Constant) and isinstance(node.value, bytes):
        return [node.value]
    if isinstance(node, (ast.Tuple, ast.List, ast.Set)):
        return [e.value for e in node.elts if isinstance(e, ast.Constant) and isinstance(e.value, bytes)]
    return []


def _magic_tag(b: bytes) -> str:
    if all(32 <= c < 127 for c in b):
        return "magic:" + b.decode("ascii")
    return "magic:0x" + b.hex()


def analyze(path: Path) -> Facts:
    """Static facts about a module. Parses the source; never imports or runs it."""
    src = Path(path).read_text(encoding="utf-8", errors="replace")
    f = Facts(Path(path), lines=src.count("\n") + 1)
    f.flag_scan = bool(_FLAG_SCAN_RE.search(src))
    try:
        tree = ast.parse(src, filename=str(path))
    except SyntaxError as e:
        f.syntax_error = f"line {e.lineno}: {e.msg}"
        return f
    f.docstring = ast.get_docstring(tree) or ""
    for node in _module_level(tree.body):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            f.defs.append(node.name)
        elif isinstance(node, ast.ClassDef) and not node.name.startswith("_"):
            f.classes.append(node.name)
        elif _is_main_guard(node):
            f.has_main = True
    for node in tree.body:               # unconditional imports only: a guarded import is optional
        if isinstance(node, ast.Import):
            f.imports.update(a.name.split(".")[0] for a in node.names)
        elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
            f.imports.add(node.module.split(".")[0])
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call):
            if isinstance(node, ast.Compare):
                sides = [node.left, *node.comparators]
                if any(isinstance(s, ast.Attribute) and s.attr == "suffix" for s in sides):
                    for s in sides:
                        f.exts.update(x.lower() for x in _strs(s) if _EXT_RE.match(x))
            continue
        fn = node.func
        name = fn.attr if isinstance(fn, ast.Attribute) else (fn.id if isinstance(fn, ast.Name) else "")
        if name == "which" and node.args:
            f.which.update(s for s in _strs(node.args[0]) if s and "/" not in s)
        elif name in _SUBPROC_FUNCS and isinstance(fn, ast.Attribute) and isinstance(fn.value, ast.Name) \
                and fn.value.id == "subprocess" and node.args and isinstance(node.args[0], (ast.List, ast.Tuple)) \
                and node.args[0].elts:
            first = node.args[0].elts[0]
            if isinstance(first, ast.Constant) and isinstance(first.value, str) and "/" not in first.value:
                f.subprocess_tools.add(first.value)
        elif name == "endswith" and node.args:
            f.exts.update(x.lower() for x in _strs(node.args[0]) if _EXT_RE.match(x))
        elif name == "startswith" and node.args:
            f.magics.update(_magic_tag(b) for b in _bytes(node.args[0]) if len(b) >= 2)
    return f


def _repo_module_names(root: Path) -> set[str]:
    names = {"ctf", "solvers", "tools", "tests", "conftest"}
    for d in layout.sys_path(root)[:-1] + [str(root / "tests")]:
        p = Path(d)
        if p.is_dir():
            names.update(x.stem for x in p.glob("*.py"))
            names.update(x.name for x in p.iterdir() if x.is_dir() and (x / "__init__.py").exists())
    return names


def needs_tools(facts: Facts, repo_names: set[str]) -> list[str]:
    std = set(sys.stdlib_module_names) | {"__future__"}
    py = {f"py:{m}" for m in facts.imports if m not in std and m not in repo_names}
    bins = {t for t in facts.which | facts.subprocess_tools if t not in _BASE_UTILS}
    return sorted(py | bins)


def classify(facts: Facts) -> str:
    tokens = set(facts.path.stem.split("_"))
    first_para = facts.docstring.split("\n\n", 1)[0]
    if tokens & _PLAN_NAME_TOKENS or _PLAN_DOC_RE.search(first_para):
        return "plan"
    if not facts.has_main:
        return "library"
    return "executes" if facts.flag_scan else "analysis"


def topic_tags(facts: Facts, doc_text: str, limit: int = 10) -> list[str]:
    text = (facts.docstring[:3000] + "\n" + doc_text).lower()
    found = [w for w in TOPIC_VOCAB if re.search(rf"(?<![a-z0-9]){re.escape(w)}(?![a-z0-9])", text)]
    return found[:limit]


def cost_class(needs: list[str], facts: Facts) -> str:
    if set(needs) & _HEAVY:
        return "heavy"
    if needs or facts.lines > 1500:
        return "medium"
    return "cheap"


def lane_of(module: Path, root: Path) -> str:
    rel = module.relative_to(root).parts
    return rel[1] if rel[0] == "solvers" else rel[0]


def engine_id(module: Path, root: Path) -> str:
    lane = lane_of(module, root).replace("-", "_").lower()
    name = re.sub(r"[^a-z0-9_]", "_", module.stem.lower())
    return f"{lane}.{name}"


def _co_fire(a: legacy_routes.LegacyRoute, b: legacy_routes.LegacyRoute) -> bool:
    """Whether a description that fires `a` always fires `b` too, or the reverse: categories overlap
    and a keyword of one contains a keyword of the other (equal keywords included)."""
    if a.category and b.category and not set(a.category) & set(b.category):
        return False
    return any(x in y or y in x for x in a.keywords for y in b.keywords)


def assign_priorities(routes: list[legacy_routes.LegacyRoute]) -> dict[int, int]:
    """index in `routes` -> priority, reproducing triage's order (see module docstring)."""
    prio: dict[int, int] = {}
    for i, r in enumerate(routes):
        if r.kind == "category":
            prio[i] = max(1, 49 - r.order)
        elif r.kind == "append":
            prio[i] = 20
        elif r.kind == "insert":
            prio[i] = 50
    nudges = sorted((i for i, r in enumerate(routes) if r.kind == "nudge"), key=lambda i: routes[i].order)
    unguarded = [i for i in nudges if not routes[i].category]
    for n, i in enumerate(unguarded):
        r = routes[i]
        p = 60
        for j in unguarded[:n]:
            o = routes[j]
            if o.path != r.path and _co_fire(r, o):
                p = max(p, prio[j] + 1)
        prio[i] = p
    p = max((prio[i] for i in unguarded), default=59)
    for i in nudges:
        if routes[i].category:
            p += 1
            prio[i] = p
    over = [routes[i].path for i in nudges if prio[i] > 100]
    if over:
        raise ValueError(f"nudge priority for {over[0]} exceeds 100; too many overlapping nudges")
    return prio


def _toml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def _toml_list(xs) -> str:
    return "[" + ", ".join(_toml_str(x) for x in xs) + "]"


def render_manifest(*, mid: str, lane: str, entry: str, capabilities, inputs, needs, cost: str,
                    status: str, routes: list[tuple[str, dict]], notes: list[str] = ()) -> str:
    out = [HEADER]
    out += [f"# {n}\n" for n in notes]
    out.append(f"id = {_toml_str(mid)}\n")
    out.append(f"lane = {_toml_str(lane)}\n")
    out.append(f"entry = {_toml_str(entry)}\n")
    out.append(f"capabilities = {_toml_list(capabilities)}\n")
    out.append(f"inputs = {_toml_list(inputs)}\n")
    out.append(f"needs_tools = {_toml_list(needs)}\n")
    out.append(f"cost_class = {_toml_str(cost)}\n")
    out.append(f"status = {_toml_str(status)}\n")
    for comment, r in routes:
        out.append(f"\n[[routes]]  # {comment}\n")
        for k in ("category", "keywords", "files"):
            if r.get(k):
                out.append(f"{k} = {_toml_list(r[k])}\n")
        out.append(f"priority = {r['priority']}\n")
    return "".join(out)


@dataclass
class Planned:
    module: Path
    sidecar: Path
    text: str


def plan(root: Path | None = None, *, triage_path: Path | None = None) -> tuple[list[Planned], list[str]]:
    """(manifests to write, skipped-module reasons) for every engine module without a sidecar, plus,
    when `triage_path` names a carried keyword router, the tools/ scripts it routes. Raises if that
    router routes a file that does not exist."""
    from . import fileroutes
    root = paths.repo_root() if root is None else Path(root)
    lroutes = legacy_routes.parse(triage_path) if triage_path is not None else []
    prio = assign_priorities(lroutes)
    by_path: dict[str, list[tuple[int, legacy_routes.LegacyRoute]]] = defaultdict(list)
    for i, r in enumerate(lroutes):
        by_path[r.path].append((i, r))
    missing = sorted(p for p in by_path if not (root / p).is_file())
    if missing:
        raise FileNotFoundError("ctf/triage.py routes files that do not exist: " + ", ".join(missing))
    modules = layout.engine_modules(root)
    modules += sorted({root / p for p in by_path if p.startswith("tools/")} - set(modules))
    repo_names = _repo_module_names(root)
    out, skipped, pending = [], [], []
    for mod in modules:
        side = _manifest.sidecar_for(mod)
        if side.exists():
            continue
        facts = analyze(mod)
        rel = mod.relative_to(root).as_posix()
        notes = []
        if facts.syntax_error:
            skipped.append(f"{rel}: does not parse ({facts.syntax_error})")
            continue
        cls = classify(facts)
        if facts.has_main:
            entry = f"cli:python {rel}"
        else:
            fn = next((n for n in _ENTRY_PREF if n in facts.defs), None) or \
                (facts.defs[0] if facts.defs else (facts.classes[0] if facts.classes else None))
            if fn is None:
                skipped.append(f"{rel}: no __main__ block and no public function or class")
                continue
            entry = ".".join(Path(rel).with_suffix("").parts) + ":" + fn
            notes.append(f"import-only: {fn} is its main public callable, not a contract entry; "
                         "`ctf run` refuses library engines")
        doc_md = root / "docs" / "toolkits" / f"{mod.stem}.md"
        doc_text = "\n".join(doc_md.read_text(encoding="utf-8", errors="replace").splitlines()[:60]) \
            if doc_md.is_file() else ""
        caps = [cls]
        if facts.has_main:
            caps += ["cli", "legacy-output"]
        if doc_text:
            caps.append("documented")
        caps += [t for t in topic_tags(facts, doc_text) if t not in caps]
        needs = needs_tools(facts, repo_names)
        inputs = sorted(f"ext:{e}" for e in facts.exts)[:12] + sorted(facts.magics)[:6]
        routes = []
        for i, r in sorted(by_path.get(rel, []), key=lambda t: (t[1].kind != "category", t[1].order)):
            if r.kind == "category":
                comment = f"triage.py CATEGORY_ENGINES[{r.category[0]!r}] position {r.order}"
            else:
                word = {"append": "appended", "insert": "insert"}.get(r.kind, "nudge")
                comment = f"triage.py suggest() {word} #{r.order}" + \
                          (f" (only when category is {r.category[0]})" if r.category else "")
            routes.append((comment, {"category": list(r.category), "keywords": list(r.keywords),
                                     "priority": prio[i]}))
        files = fileroutes.distinctive(facts.exts, facts.magics) if not routes else []
        if len(files) > fileroutes.MAX_MATCHERS:
            files = []
        pending.append((mod, side, notes, dict(
            mid=engine_id(mod, root), lane=lane_of(mod, root), entry=entry, capabilities=caps,
            inputs=inputs, needs=needs, cost=cost_class(needs, facts),
            status="plan-only" if cls == "plan" else "active", routes=routes), files))
    # inferred file routes, given priorities that no existing route on the same matcher holds
    existing, _problems = _manifest.scan(root)
    fprio, fskipped = fileroutes.assign([(str(mod), files) for mod, _, _, _, files in pending if files],
                                        fileroutes.taken_priorities(existing))
    skipped += fskipped
    for mod, side, notes, kw, files in pending:
        if str(mod) in fprio:
            kw["routes"].append((fileroutes.COMMENT, {"files": files, "priority": fprio[str(mod)]}))
        text = render_manifest(notes=notes, **kw)
        _manifest.parse(__import__("tomllib").loads(text), side)       # never write an invalid file
        out.append(Planned(mod, side, text))
    return out, skipped


def write(planned: list[Planned]) -> int:
    for p in planned:
        if p.sidecar.exists():
            raise FileExistsError(f"{p.sidecar} appeared while generating; not overwriting")
        p.sidecar.write_text(p.text, encoding="utf-8")
    return len(planned)
