"""Write a manifest for every engine module that lacks one.

    python -m ctf engines generate [--dry-run]     (then the files generated from the manifests:
                                                    ctf/engines/derived.py)

Everything in a generated manifest is inferred, and the file says so in its header:

- `entry`: a module with an `if __name__ == "__main__"` block is a carried CLI script
  (`cli:python solvers/<lane>/<name>.py`, tagged `legacy-output`: it prints free text, not the
  SolverResult JSON the contract asks of new CLI engines). A module without one is import-only
  (`library`): its entry names its main public function and `ctf run` refuses to call it.
- `capabilities`: one class tag, `executes` (CLI that scans its output for flags), `analysis` (CLI that
  reports facts), `plan` (planner/builder: prints candidates, never runs them), or `library`; then
  `cli`, `legacy-output`, `documented` (a docs/toolkits/<name>.md exists) and topic words from a fixed
  vocabulary found in the docstring and that doc.
- `inputs`: extensions and magic bytes the code compares against (`.endswith`, `.suffix ==`,
  `.startswith(b"...")`).
- `needs_tools`: unconditional module-level third-party imports (`py:<module>`), `shutil.which("x")`
  literals, and literal argv[0] of subprocess calls (base utilities excluded).
- `cost_class`: heavy for sage/angr/ghidra/docker/torch/hashcat/john/volatility, medium for any other
  external need or a module over 1500 lines, else cheap.
- `routes`: when plan() is given a carried keyword router (`triage_path`, a triage.py in the shape
  legacy_routes.py reads), exactly the routes it hard-codes for the module, with priorities that
  reproduce its order (category lists 49 down by position; a keyword insert that applies only when
  the engine is not listed yet 50, above every list and below every nudge; keyword nudges from 60 up,
  a later nudge above an earlier one whose keyword it contains or is contained in; nudges guarded by a
  category, which the carried router ran after all the others, above every unguarded nudge and
  strictly rising in source order; an appended nudge 20). B-186
  generated the carried manifests that way from the old ctf/triage.py; since R-10 the manifests are
  the routing source and ctf/triage.py hard-codes nothing. Otherwise, a file route inferred from the
  distinctive formats the code tests for (fileroutes.py). A module with neither gets no route, and
  lint reports it.

Regeneration never overwrites an existing manifest: once written, the sidecar is the source of truth.
"""
