"""The machine-checked engine coverage matrix, docs/coverage/ENGINES.md.

    python -m ctf engines coverage --write     regenerate it
    python -m ctf engines coverage --check     exit 1 when the file is stale

Built only from the manifests and the test files, so it is deterministic: no dates, no run results.
tests/test_engines_coverage.py fails when the committed file differs from a fresh render. Real-use
counts come from each event's ledger instead (`python -m ctf engines usage`).
"""
from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

from .. import paths
from . import layout, manifest as _manifest
from .generate import CLASS_TAGS

MATRIX_REL = "docs/coverage/ENGINES.md"

_IMPORT_RE = re.compile(r"(?m)^[ \t]*(?:from[ \t]+([\w.]+)[ \t]+import|import[ \t]+([\w., \t]+))")
_IMPORT_MODULE_RE = re.compile(r"""import_module\(\s*["']([\w.]+)["']""")
_PATH_RE = re.compile(r"(?:solvers/[\w-]+|tools)/\w+\.py")
_DOTTED_RE = re.compile(r"solvers\.([\w-]+)\.(\w+)")


def tests_referencing(root: Path | None = None) -> dict[Path, set[str]]:
    """module path -> test files (repo-relative) that import it or name its path.

    A flat import is credited to the file it resolves to on the engine sys.path (layout.flat_owner),
    the same file the test suite imports."""
    root = paths.repo_root() if root is None else Path(root)
    owner_cache: dict[str, Path | None] = {}

    def owner(name: str) -> Path | None:
        if name not in owner_cache:
            owner_cache[name] = layout.flat_owner(name, root)
        return owner_cache[name]

    refs: dict[Path, set[str]] = defaultdict(set)
    tests = root / "tests"
    if not tests.is_dir():
        return refs
    for tf in sorted(tests.rglob("*.py")):
        rel = tf.relative_to(root).as_posix()
        src = tf.read_text(encoding="utf-8", errors="replace")
        names = set()
        for frm, imp in _IMPORT_RE.findall(src):
            if frm:
                names.add(frm.split(".")[0])
            else:
                names.update(x.strip().split(" ")[0].split(".")[0] for x in imp.split(",") if x.strip())
        names.update(m.split(".")[0] for m in _IMPORT_MODULE_RE.findall(src))
        for n in names:
            o = owner(n)
            if o is not None:
                refs[o].add(rel)
        for p in _PATH_RE.findall(src):
            if (root / p).is_file():
                refs[root / p].add(rel)
        for lane, name in _DOTTED_RE.findall(src):
            cand = root / "solvers" / lane / f"{name}.py"
            if cand.is_file():
                refs[cand].add(rel)
    return refs


def _class(m: _manifest.Manifest) -> str:
    return next((c for c in m.capabilities if c in CLASS_TAGS), "?")


def _route_cats(m: _manifest.Manifest) -> str:
    if not m.routes:
        return "UNROUTED"
    cats = sorted({c for r in m.routes for c in r.category})
    if any(not r.category for r in m.routes):
        cats.append("any")
    return ", ".join(cats)


def _cell(s: str) -> str:
    return s.replace("|", "\\|")


def render(root: Path | None = None) -> str:
    root = paths.repo_root() if root is None else Path(root)
    ms = _manifest.discover(root)
    refs = tests_referencing(root)
    by_lane: dict[str, list[_manifest.Manifest]] = defaultdict(list)
    for m in ms:
        by_lane[m.lane].append(m)
    unmanifested = [p.relative_to(root).as_posix() for p in layout.engine_modules(root)
                    if not _manifest.sidecar_for(p).exists()]

    out = [
        "# Engine coverage matrix\n\n",
        "Generated by `python -m ctf engines coverage --write` from the engine manifests\n",
        "(`<module>.manifest.toml`) and the test files. Do not edit by hand:\n",
        "`tests/test_engines_coverage.py` fails when this file is stale. After a merge that touches\n",
        "engines, regenerate it instead of resolving conflicts line by line.\n\n",
        "- **class**: `executes` (a CLI that scans its output for flags), `analysis` (a CLI that reports\n",
        "  facts), `plan` (builds candidates, never runs them), `library` (import-only; `ctf run` refuses\n",
        "  it). Inferred for the carried engines (ctf/engines/generate.py); a manifest can correct it.\n",
        "- **routes**: the categories its `[[routes]]` name; `any` = a keyword route valid in every\n",
        "  category; `UNROUTED` = triage never suggests it.\n",
        "- **tests**: test files that import the module or name its path. 0 = no test reaches it.\n",
        "- Real use in play is not here: each run of `ctf run` / `ctfpy` appends `engine.run` to the event\n",
        "  ledger; `python -m ctf engines usage` reports it.\n\n",
        "## Summary\n\n",
        "| lane | engines | executes | analysis | plan | library | routed | unrouted | with tests | no tests |\n",
        "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n",
    ]
    totals = [0] * 9
    for lane in sorted(by_lane):
        group = by_lane[lane]
        cls = [_class(m) for m in group]
        routed = sum(1 for m in group if m.routes)
        tested = sum(1 for m in group if refs.get(m.module_path))
        row = [len(group), cls.count("executes"), cls.count("analysis"), cls.count("plan"),
               cls.count("library"), routed, len(group) - routed, tested, len(group) - tested]
        totals = [a + b for a, b in zip(totals, row)]
        out.append(f"| {lane} | " + " | ".join(str(x) for x in row) + " |\n")
    out.append("| **total** | " + " | ".join(f"**{x}**" for x in totals) + " |\n")
    if unmanifested:
        out.append("\n**Engine modules without a manifest** (lint error `unmanifested-engine`):\n\n")
        out += [f"- `{p}`\n" for p in unmanifested]
    for lane in sorted(by_lane):
        out.append(f"\n## {lane}\n\n")
        out.append("| engine | class | status | cost | routes | needs | tests |\n")
        out.append("|---|---|---|---|---|---|---:|\n")
        for m in sorted(by_lane[lane], key=lambda m: m.id):
            needs = ", ".join(m.needs_tools) if m.needs_tools else ""
            out.append(f"| `{m.id}` | {_class(m)} | {m.status} | {m.cost_class} | {_cell(_route_cats(m))} | "
                       f"{_cell(needs)} | {len(refs.get(m.module_path, ()))} |\n")
    return "".join(out)


def matrix_path(root: Path | None = None) -> Path:
    return (paths.repo_root() if root is None else Path(root)) / MATRIX_REL


def write(root: Path | None = None) -> Path:
    p = matrix_path(root)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render(root), encoding="utf-8")
    return p


def is_stale(root: Path | None = None) -> bool:
    p = matrix_path(root)
    return not p.exists() or p.read_text(encoding="utf-8") != render(root)
