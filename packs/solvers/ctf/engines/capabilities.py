"""docs/CAPABILITIES.md, the capability map, generated from the engine manifests (R-10).

    python -m ctf engines generate            writes it (with the route table and the matrix)
    python -m ctf engines generate --check    exit 1 when a generated file is stale

Every row comes from a manifest (id, class tag, status, topic tags, routes, needs) plus the first
sentence of the engine module's docstring for "what it does". Deterministic: no dates, no run
results. tests/test_engines_capabilities.py fails when the committed file differs from a fresh render.
"""
from __future__ import annotations

import ast
import re
from collections import defaultdict
from pathlib import Path

from .. import paths
from . import manifest as _manifest
from .routetable import engine_class

CAPABILITIES_REL = "docs/CAPABILITIES.md"
CARRIED_REL = "docs/capabilities-carried.md"
SUMMARY_CHARS = 140
TRIGGER_KEYWORDS = 6
_CLASS_TAGS = {"executes", "analysis", "plan", "library", "cli", "legacy-output", "documented"}


def summary(module: Path) -> str:
    """The first sentence of a module's docstring, on one line, at most SUMMARY_CHARS characters."""
    try:
        tree = ast.parse(Path(module).read_text(encoding="utf-8", errors="replace"))
    except (OSError, SyntaxError):
        return ""
    doc = ast.get_docstring(tree) or ""
    para = " ".join(doc.strip().split("\n\n", 1)[0].split())
    m = re.search(r"(?<=[.!?])\s", para)
    first = para[: m.start()] if m else para
    if len(first) > SUMMARY_CHARS:
        first = first[: SUMMARY_CHARS - 1].rstrip() + "…"
    return first


def _cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def _code(s: str) -> str:
    """`s` as inline code, safe in a table cell (a backtick inside widens the fence)."""
    s = s.replace("|", "\\|")
    return f"`` {s} ``" if "`" in s else f"`{s}`"


def _trigger(r: _manifest.Route) -> str:
    parts = []
    if r.keywords:
        shown = ", ".join(_code(k.strip() or k) for k in r.keywords[:TRIGGER_KEYWORDS])
        more = len(r.keywords) - TRIGGER_KEYWORDS
        parts.append(shown + (f" +{more} more" if more > 0 else ""))
    if r.files:
        parts.append("file " + ", ".join(_code(f) for f in r.files))
    return " and ".join(parts) if parts else "always"


def _topics(m: _manifest.Manifest) -> list[str]:
    return [c for c in m.capabilities if c not in _CLASS_TAGS]


def _engine_cell(m: _manifest.Manifest, root: Path) -> str:
    return f"[`{m.id}`](../{m.rel_module(root)})"


def render(root: Path | None = None, manifests: list[_manifest.Manifest] | None = None) -> str:
    from .. import triage
    root = paths.repo_root() if root is None else Path(root)
    ms = sorted(_manifest.discover(root) if manifests is None else manifests, key=lambda m: m.id)
    live = [m for m in ms if m.status != "retired"]
    retired = [m for m in ms if m.status == "retired"]
    what = {m.id: _cell(summary(m.module_path)) for m in ms}

    by_cat: dict[str, list[tuple[_manifest.Manifest, _manifest.Route]]] = defaultdict(list)
    anycat: dict[str, list[_manifest.Route]] = defaultdict(list)
    for m in live:
        for r in m.routes:
            if r.matches_everything:
                continue
            if r.category:
                for c in r.category:
                    by_cat[c].append((m, r))
            else:
                anycat[m.id].append(r)
    cats = [c for c in triage.CATEGORIES if c in by_cat] + sorted(set(by_cat) - set(triage.CATEGORIES))
    unrouted = [m for m in live if not m.routes]
    by_id = {m.id: m for m in ms}

    out = [
        "# Capability map\n\n",
        "Generated by `python -m ctf engines generate` from the engine manifests (`<module>.manifest.toml`)\n",
        "and the first sentence of each engine's docstring. Do not edit by hand:\n",
        "`tests/test_engines_capabilities.py` fails when this file is stale. After a merge that touches\n",
        "engines, regenerate it instead of resolving conflicts line by line.\n\n",
        "This is what `python -m ctf triage` (ctf/triage.py) can suggest, and when. Triage lists every engine\n",
        "whose route matches the challenge, best priority first: routes that name a category apply only\n",
        "there, keyword routes need a word of the description, file routes need a downloaded file.\n\n",
        "- **class**: `executes` (a CLI that scans its output for flags), `analysis` (a CLI that reports\n",
        "  facts), `plan` (builds candidates, never runs them), `library` (import-only: call it from Python;\n",
        "  `ctf run` refuses it).\n",
        "- **priority**: the route's priority (0-100, higher is listed first).\n",
        "- **when**: `always` = suggested for every challenge of that category; otherwise the keywords\n",
        "  (lower-case substrings of the description) or the file matchers (`ext:`, `magic:`, `name:`).\n",
        "- Per-engine detail (status, cost, needs, tests) is in [coverage/ENGINES.md](coverage/ENGINES.md);\n",
        "  the hand-written map carried from CSCTF 2026 is kept, unmaintained, in\n",
        f"  [{Path(CARRIED_REL).name}]({Path(CARRIED_REL).name}).\n\n",
        "## Summary\n\n",
        "| category | engines | always | on a keyword or file |\n",
        "|---|---:|---:|---:|\n",
    ]
    for c in cats:
        ids = {m.id for m, _ in by_cat[c]}
        always = {m.id for m, r in by_cat[c] if not (r.keywords or r.files)}
        out.append(f"| {c} | {len(ids)} | {len(always)} | {len(ids - always)} |\n")
    out.append(f"| any category | {len(anycat)} | 0 | {len(anycat)} |\n")
    out.append(f"\n{len(ms)} engines: {len(live) - len(unrouted)} routed, {len(unrouted)} not routed, "
               f"{len(retired)} retired.\n")

    for c in cats:
        out.append(f"\n## {c}\n\n")
        out.append(f"Playbook: [playbooks/{c}.md](playbooks/{c}.md).\n\n")
        out.append("| engine | class | priority | when | what it does |\n|---|---|---:|---|---|\n")
        rows = sorted(by_cat[c], key=lambda mr: (-mr[1].effective_priority, mr[0].id, _trigger(mr[1])))
        for m, r in rows:
            out.append(f"| {_engine_cell(m, root)} | {engine_class(m)} | {r.effective_priority} | "
                       f"{_trigger(r)} | {what[m.id]} |\n")

    out.append("\n## Any category\n\n")
    out.append("Routes with no category condition: suggested in every category when the description or a\n"
               "downloaded file matches.\n\n")
    out.append("| engine | class | priority | when | what it does |\n|---|---|---:|---|---|\n")
    for mid in sorted(anycat):
        m = by_id[mid]
        for r in sorted(anycat[mid], key=lambda r: (-r.effective_priority, _trigger(r))):
            out.append(f"| {_engine_cell(m, root)} | {engine_class(m)} | {r.effective_priority} | "
                       f"{_trigger(r)} | {what[mid]} |\n")

    out.append("\n## Not routed\n\n")
    out.append("No route yet, so triage never suggests them (lint `no-route`, baselined in\n"
               "`docs/coverage/lint-baseline.txt`). Reach them with `python -m ctf run <id>` or from Python.\n")
    by_lane: dict[str, list[_manifest.Manifest]] = defaultdict(list)
    for m in unrouted:
        by_lane[m.lane].append(m)
    for lane in sorted(by_lane):
        out.append(f"\n### {lane}\n\n| engine | class | what it does |\n|---|---|---|\n")
        for m in by_lane[lane]:
            out.append(f"| {_engine_cell(m, root)} | {engine_class(m)} | {what[m.id]} |\n")

    if retired:
        out.append("\n## Retired\n\n")
        out += [f"- {_engine_cell(m, root)}: {what[m.id]}\n" for m in retired]

    topics: dict[str, list[str]] = defaultdict(list)
    for m in live:
        for t in _topics(m):
            topics[t].append(m.id)
    out.append("\n## Topic index\n\n")
    out.append("Topic tags from the manifests' `capabilities` (inferred from docstrings for the carried\n"
               "engines; a manifest can correct them).\n\n")
    for t in sorted(topics):
        out.append(f"- **{t}**: " + ", ".join(f"`{i}`" for i in sorted(topics[t])) + "\n")
    out.append(_toolbox_section(root))
    return "".join(out)


def _toolbox_section(root: Path) -> str:
    """The binary toolbox (B-142) from root/tools/toolbox.toml; a missing or bad manifest is named
    in the section, never dropped."""
    from .. import toolbox
    try:
        return toolbox.capabilities_section(toolbox.load(toolbox.manifest_path(root)))
    except toolbox.ToolboxError as e:
        return toolbox.capabilities_section(None, missing_reason=str(e).replace(str(root), "<repo>"))


def path(root: Path | None = None) -> Path:
    return (paths.repo_root() if root is None else Path(root)) / CAPABILITIES_REL


def write(root: Path | None = None) -> Path:
    p = path(root)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render(root), encoding="utf-8")
    return p


def is_stale(root: Path | None = None) -> bool:
    p = path(root)
    return not p.exists() or p.read_text(encoding="utf-8") != render(root)
